// G1 채점 — 봉인⑥ 조각 대조 · 봉인④-b 게이트, 계열별 (오종래 2026-10-14)
//   인문: ① 실체 글자 · ② 판정불가(교사 판정) · ④ K 핵심어 + 경로 흔적 · 게이트 ④X→②, ②X→①
//   수리: ①②③ 답 인식 노드 일치(2026-09-30 그대로) · ④ K 글자(「의 값」을 뗀 마지막 어절) · 게이트 ④X→③, ③X→②, ②X→①

import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import type { PathNode } from '../src/fq/v2/graph.ts';
import { grade } from '../src/rubric/g1.ts';
import { 게이트사슬, 봉인4b_게이트, 수리K글자 } from '../src/rubric/sealed/g1.ts';
import type { 급소K, 조각 } from '../src/rubric/types.ts';

const 노드 = (id: string, entity: string, color: PathNode['color'] = 'B') => ({ id, entity, color, surface: '', switchId: '1', index: 0 }) as PathNode;
const 조각of = (c: Partial<조각> & Pick<조각, 'id' | '파트' | '배점'>): 조각 => ({
  요소: null, 수행질: null, 확인물음: '', 충족조건: '', is_중심: false, node: null, 모범조각: '', ...c,
});
const K: 급소K = { 실체: 'B국이 시행한 대응조치', node: 노드('n2', 'B국이 시행한 대응조치') };

const 인문루브릭: 조각[] = [
  조각of({ id: '근거대기-1', 파트: '근거대기', 요소: 'b', 배점: 2, node: 노드('n1', 'A국의 보호무역 정책으로 인한 손실') }),
  조각of({ id: '근거대기-2', 파트: '근거대기', 요소: 'b', 배점: 2, 제시문: { 단락: '다', 단락급소: 'B국' } }),
  조각of({ id: '세우기-1', 파트: '세우기', 요소: 'p', 배점: 3, 근거: { 단락: '다', 단락급소: 'B국', 문장: 'B국은 …' } }),
  조각of({
    id: '답구하기-1', 파트: '답구하기', 요소: 'k', 배점: 3, node: K.node,
    경로: [
      { 출처: '제시문', 색: 'b', 실체: 'B국', 단락: '다' },
      { 출처: '논제', 색: 'b', 실체: 'A국의 보호무역 정책으로 인한 손실' },
      { 출처: '논제', 색: 'k', 실체: 'B국이 시행한 대응조치', 핵심어: '대응조치' },
    ],
  }),
];

describe('G1 인문 — 흔적 글자 · 세우기 교사 판정 · 게이트 ④X→②', () => {
  it('① 실체 글자(노드 · 제시문 단락 급소) · ② 판정불가 · ④ K 핵심어 + 경로 흔적', () => {
    const r = grade('B국은 A국의 보호무역 정책으로 인한 손실을 줄이려고 대응조치를 시행했다.', 인문루브릭, '', K, '인문사회국어');
    const 결과 = Object.fromEntries(Object.values(r.파트별).flatMap((p) => p.조각별).map((x) => [x.조각id, x.결과]));
    assert.deepEqual(결과, { '근거대기-1': 'O', '근거대기-2': 'O', '세우기-1': '판정불가', '답구하기-1': 'O' });
    assert.deepEqual(r.판정불가, ['세우기-1']);
  });

  it('④ K 핵심어가 없으면 X → 세우기 상한 (풀기를 건너뛴다)', () => {
    const r = grade('B국은 A국의 보호무역 정책으로 인한 손실을 겪었다.', 인문루브릭, '', K, '인문사회국어');
    assert.equal(r.파트별.답구하기.조각별[0].결과, 'X');
    assert.equal(r.파트별.세우기.상한, 1); // 세우기 배점 3 × 1/3
    assert.equal(r.파트별.근거대기.상한, null);
    assert.equal(r.무너진지점, '답구하기');
  });

  it('④ 경로 흔적이 하나도 없으면 X', () => {
    const r = grade('정부의 대응조치가 필요하다.', 인문루브릭, '', K, '인문사회국어');
    assert.equal(r.파트별.답구하기.조각별[0].결과, 'X');
    assert.match(r.파트별.답구하기.조각별[0].판단근거, /경로 흔적 없음/);
  });

  it('게이트 사슬 — 인문 ④→②→①, 수리 ④→③→②→①', () => {
    assert.deepEqual(게이트사슬('인문사회국어'), [['답구하기', '세우기'], ['세우기', '근거대기']]);
    assert.deepEqual(게이트사슬('수리'), [['답구하기', '풀기'], ['풀기', '세우기'], ['세우기', '근거대기']]);
    const 상한 = 봉인4b_게이트(
      [{ 조각id: 's', 파트: '세우기', 요소: 'p', 결과: 'X', 배점: 3, 득점: 0, 판단근거: '' }],
      { 근거대기: 4, 세우기: 3, 풀기: 0, 답구하기: 3 },
      '인문사회국어',
    );
    assert.deepEqual(상한, { 근거대기: 1.3 });
  });
});

describe('G1 수리 — ④ K 글자 (값은 교사 확인)', () => {
  it('K 글자 = 머리 쉼표 · 끝 「의 값」「값」을 뗀 마지막 어절', () => {
    assert.equal(수리K글자(', f(2)의 값'), 'f(2)');
    assert.equal(수리K글자(', 상수 a'), 'a');
    assert.equal(수리K글자('p+q의 값'), 'p+q');
  });

  it('④ — 답에 K 글자가 있으면 O, 없으면 X (GJ를 쓰지 않는다)', () => {
    const 수리K: 급소K = { 실체: ', f(2)의 값', node: 노드('n4', ', f(2)의 값') };
    const 루브릭 = [조각of({ id: '답구하기-1', 파트: '답구하기', 요소: 'k', 배점: 1, node: 수리K.node })];
    assert.equal(grade('f(2) = 33', 루브릭, '', 수리K, '수리').파트별.답구하기.조각별[0].결과, 'O');
    assert.equal(grade('답은 33이다', 루브릭, '', 수리K, '수리').파트별.답구하기.조각별[0].결과, 'X');
  });
});
