const 가글 = '마티스와 피카소의 기질적 차이는 판이한 출신 배경과 성장 과정 속에서 형성됐다. 서로 다른 기질적 특징은 작품의 지향점에도 영향을 미쳤다.';
const 나글 = '저자의 의도를 감안한다고 해서 문학 텍스트의 의미가 발견되는 것은 아니다. 이미지, 상징, 시점, 배경, 구성 등과 같은 언어화된 증거들이 문학작품을 구성한다.';
