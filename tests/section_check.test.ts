const 표 = { 대비: ['그러나', '하지만', '반면'], 결론: ['따라서'], 기능표지: true, 분량: true, 완결: true };

const 좋은답 = [
  '(라)에서 (사)까지의 제시문은 (라), (바)와 (마), (사)의 두 부류로 구분할 수 있다.',
  '나는 과거를 중시하는 (라)와 (바)의 입장을 요약하겠다.',
  '(라)는 과거의 죽은 자들이 현재를 돕는다고 본다.',
  '(바)는 옛 경전을 공부해 밑바탕을 세워야 한다고 한다.',
  '이를 바탕으로 현재를 중시하는 입장을 비판할 수 있다.',
  '(마)는 지금 함께 있는 사람이 가장 중요하다고 한다.',
  '그러나 (라)에서 보듯 과거의 기억이 현재를 돕는다.',
  '(사)는 지금 여기에 충실하라고 한다.',
  '하지만 (바)처럼 옛 경전 없이 지금을 이해하기는 힘들다.',
  '물론 지금이 중요함은 부정할 수 없다. 그러나 과거를 버리면 현재도 흔들린다.',
  '따라서 현재만 중시하는 입장은 한계를 지닌다.',
].join(' ');

describe('구간 정합성 측정', () => {
  const m = measure_sections(좋은답, 루브릭, 표);
  it('범위 표현 「(라)에서 (사)까지」는 묶음이 아니다 — 학생 묶음 = 엔진 부류', () => {
    assert.deepEqual(m.학생묶음, [['라', '바'], ['마', '사']]);
    assert.equal(m.조각['세우기-1'].결과, 'O');
  });
  it('고른 부류 · 상대 — 선택 표지 문장에서', () => {
    assert.deepEqual(m.선택, ['라', '바']);
    assert.deepEqual(m.상대, ['마', '사']);
  });
  it('네 구간 모두 통과 → 어긋남 0 · 등급 4', () => {
    assert.deepEqual(Object.entries(m.조각).filter(([, v]) => v.결과 !== 'O').map(([k]) => k), []);
    assert.deepEqual(Object.values(m.조건).map((c) => c.결과), ['O', 'O', 'O', 'O']);
    assert.equal(m.등급, 4);
  });
  it('[라]를 반대쪽 극성으로만 말하면 근거대기 X — 어긋남이 늘어 등급이 내려간다', () => {
    // [라]만 부른 문장 모두 — 하나라도 [라] 쪽이면 O라서 비판 마디의 「(라)에서 보듯」도 바꾼다
    const 틀린 = 좋은답.replace('(라)는 과거의 죽은 자들이 현재를 돕는다고 본다.', '(라)는 지금 현재의 슬픔을 말한다.').replace('(라)에서 보듯', '(바)에서 보듯');
    const n = measure_sections(틀린, 루브릭, 표);
    assert.equal(n.조각['근거대기-1'].결과, 'X');
    assert.ok(n.등급 < 4);
  });
  it('양보 뒤 역접이 없으면 인정재반박 X', () => {
    const n = measure_sections(좋은답.replace('물론 지금이 중요함은 부정할 수 없다. ', ''), 루브릭, 표);
    assert.equal(n.조각['풀기-3'].결과, 'X');
  });
});

