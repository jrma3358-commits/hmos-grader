// 학생 경로 채점 (오종래 2026-10-21 확정 B · Hybrid) — 단계는 Claude가 나눈 꼴을 고정해 엔진 판정만 본다
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { grade_student_path, type 학생단계 } from '../src/rubric/path_grade.ts';

// q3 모범답안 루브릭 (경우의 수 · 균등 5점)
const 조각 = [
  { id: '근거대기-1', 파트: '근거대기', 배점: 1.1 },
  { id: '세우기-1', 파트: '세우기', 배점: 0.8, 줄글: '양 끝 모음 나열: 1/2! × 3P2 = 3' },
  { id: '세우기-2', 파트: '세우기', 배점: 0.9, 줄글: '나머지 4개 나열: 4!=24' },
  { id: '풀기-1', 파트: '풀기', 배점: 1.1 },
  { id: '답구하기-1', 파트: '답구하기', 배점: 1.1, 모범답: { 값: ['72'] } },
];
const 단계 = (파트: 학생단계['파트'], 글: string, 대응: string | null = null, 다경로 = false): 학생단계 => ({ 파트, 글, 대응, 다경로, 까닭: '' });

describe('학생 경로 채점', () => {
  it('풀이1 (양 끝 a,a / a,e 경우 나누기 → 24+48=72) — 5/5, 계산식 없는 근거대기는 엔진 조각 판정', () => {
    const r = grade_student_path([
      단계('근거대기', '모음은 a, a, e이다.', '근거대기-1'),
      단계('세우기', '양 끝이 a, a인 경우: 가운데 b, c, d, e를 나열하므로 4! = 24가지', null, true),
      단계('세우기', '양 끝이 a, e 또는 e, a인 경우: 가운데 a, b, c, d를 나열하므로 2 × 4! = 48가지', null, true),
      단계('풀기', '따라서 24 + 48 = 72가지', null, true),
      단계('답구하기', '따라서 24 + 48 = 72가지', '답구하기-1'),
    ], 조각, [{ 조각id: '근거대기-1', 파트: '근거대기', 결과: 'O', 판단근거: '🔆 경우 나누기' }], '72가지');
    assert.equal(r.부분점수, 5);
    assert.equal(r.만점, 5);
    assert.ok(r.조각별.every((x) => x.결과 === 'O'));
    assert.deepEqual(r.조각별.filter((x) => x.파트 === '세우기').map((x) => x.배점), [0.85, 0.85]);
  });
  it('풀이2 (2×2=4 · 4×3×2×1=24 · ∴ 4×24=96) — 세우기 · 풀기는 경로 안에서 O, 답구하기 96≠72 X, 같은 단계 값 3과 다름은 교사 참고', () => {
    const r = grade_student_path([
      단계('세우기', '양끝이 모음을 나열하는 경우의 수: 2×2=4(가지)', '세우기-1', true),
      단계('세우기', '이 때 그 사이사이에 4개의 문자를 나열하면 4×3×2×1=24(가지)', '세우기-2'),
      단계('풀기', '∴ 4×24=96(가지)', '풀기-1'),
      단계('답구하기', '∴ 4×24=96(가지)', '답구하기-1'),
    ], 조각, [{ 조각id: '근거대기-1', 파트: '근거대기', 결과: 'X' }], '72가지');
    const 판 = Object.fromEntries(r.조각별.map((x) => [x.조각id, x]));
    assert.equal(판['세우기-1'].결과, 'O');
    assert.equal(판['세우기-1'].같은단계, '불일치');
    assert.equal(판['세우기-2'].같은단계, '일치');
    assert.equal(판['풀기-1'].결과, 'O');
    assert.equal(판['답구하기-1'].결과, 'X');
    assert.equal(판['답구하기-1'].학생값, '96');
    assert.equal(판['근거대기-1'].결과, 'X'); // 단계 없음
    assert.equal(r.부분점수, 2.8);
    assert.ok(r.경고.some((w) => w.includes('교사 확인')));
  });
  it('학생4 꼴 — 근거대기 단계 없음 · 답 72 맞음 → 근거대기는 엔진 복원(엔진 O면 점수), 5/5 (오종래 2026-10-21 확정)', () => {
    const r = grade_student_path([
      단계('세우기', '(i)  a,(b,c,d,e),a → 4!', null, true),
      단계('세우기', '(ii) a,(a,b,c,d),e → 4!', null, true),
      단계('세우기', '(iii) e,(a,b,c,d),a → 4!', null, true),
      단계('풀기', '∴ 3×4! = 3×24 = 72(가지)', '풀기-1'),
      단계('답구하기', '∴ 3×4! = 3×24 = 72(가지)', '답구하기-1'),
    ], 조각, [{ 조각id: '근거대기-1', 파트: '근거대기', 결과: 'O', 판단근거: '🔆 경우 나누기' }, { 조각id: '세우기-1', 파트: '세우기', 결과: 'O' }], '72가지');
    const 근 = r.조각별.find((x) => x.파트 === '근거대기')!;
    assert.equal(근.결과, 'O');
    assert.equal(근.복원, true);
    assert.ok(근.판단근거.startsWith('답은 맞으나 풀이 조각 없음 — 엔진 복원'));
    assert.equal(r.부분점수, 5);
    assert.ok(r.경고.some((w) => w.includes('엔진 복원')));
  });
  it('답이 틀리면 복원하지 않는다 — 풀이2의 근거대기는 「단계 없음」 X', () => {
    const r = grade_student_path([단계('세우기', '2×2=4'), 단계('풀기', '∴ 4×24=96'), 단계('답구하기', '∴ 4×24=96')], 조각, [{ 조각id: '근거대기-1', 파트: '근거대기', 결과: 'O' }], '72가지');
    const 근 = r.조각별.find((x) => x.파트 === '근거대기')!;
    assert.equal(근.결과, 'X');
    assert.equal(근.복원, undefined);
  });
  it('엔진이 X로 본 파트는 복원해도 X', () => {
    const r = grade_student_path([단계('세우기', '4!=24'), 단계('풀기', '3×24=72'), 단계('답구하기', '∴ 3×24=72')], 조각, [{ 조각id: '근거대기-1', 파트: '근거대기', 결과: 'X' }], '72가지');
    const 근 = r.조각별.find((x) => x.파트 === '근거대기')!;
    assert.equal(근.결과, 'X');
    assert.equal(근.복원, true);
  });
  it('학생8 꼴 — 「[a] v v v v [e] → 4!=24」는 화살표 앞을 떼고 4!=24로 계산 검증, 대응 조각(엔진 X)과 상관없이 O (오종래 2026-10-21 확정)', () => {
    const 단계들 = (대응: string | null) => [
      단계('근거대기', '양 끝에 모음을 나열하면', '근거대기-1'),
      단계('세우기', '[a] v v v v [e] → 4!=24', 대응, true),
      단계('세우기', '[e] v v v v [a] → 4!=24', 대응, true),
      단계('풀기', '∴ 24+24=48(가지)', '풀기-1'),
      단계('답구하기', '∴ 24+24=48(가지)', '답구하기-1'),
    ];
    const 엔진 = [{ 조각id: '근거대기-1', 파트: '근거대기', 결과: 'X' as const }, { 조각id: '세우기-1', 파트: '세우기', 결과: 'X' as const }, { 조각id: '세우기-2', 파트: '세우기', 결과: 'O' as const }];
    const 점수들 = [null, '세우기-1', '세우기-2'].map((d) => grade_student_path(단계들(d), 조각, 엔진, '72가지'));
    for (const r of 점수들) {
      assert.deepEqual(r.조각별.filter((x) => x.파트 === '세우기').map((x) => x.결과), ['O', 'O']);
      assert.equal(r.부분점수, 2.8);
    }
    assert.ok(점수들[0].조각별.find((x) => x.파트 === '세우기')!.판단근거.startsWith('계산 맞음 — 4!=24'));
  });
  it('「2!×4!=48」 · 「→ 2!×4!=46」 — 화살표 뒤 계산식 양변 검증 (맞으면 O, 틀리면 X)', () => {
    const r = grade_student_path([단계('세우기', '양 끝 a,e → 2!×4!=48'), 단계('풀기', 'ii) 경우 → 2!×4!=46'), 단계('답구하기', '∴ 72')], 조각, [], '72가지');
    assert.equal(r.조각별.find((x) => x.파트 === '세우기')!.결과, 'O');
    assert.equal(r.조각별.find((x) => x.파트 === '풀기')!.결과, 'X');
  });
  it('계산이 틀린 단계는 X · 정답이 없으면 모범 끝 값으로 · 둘 다 없으면 판정불가', () => {
    const r = grade_student_path([단계('세우기', '4!=12'), 단계('답구하기', '∴ 72가지')], 조각, [], null);
    assert.equal(r.조각별.find((x) => x.파트 === '세우기')!.결과, 'X');
    assert.equal(r.조각별.find((x) => x.파트 === '답구하기')!.결과, 'O'); // 「=」 없는 결론 줄 끝 수 72 — 모범 끝 값 72와 같다
    const q = grade_student_path([단계('답구하기', '∴ 3×24=72')], 조각.map((c) => ({ ...c, 모범답: null })), [], null);
    assert.equal(q.조각별.find((x) => x.파트 === '답구하기')!.결과, '판정불가');
  });
});
