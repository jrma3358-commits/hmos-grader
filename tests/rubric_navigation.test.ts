// 과거현재 C-1a: 「[라]~[사]를 입장이 유사한 두 부류로 묶어 그 중 한 입장을 선택해 요약하고, 이를 바탕으로 다른 입장을 비판하시오.」
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { recognizeV2Analysis } from '../src/fq/pipeline.ts';
import { derive_pieces, f2_input_from_v2 } from '../src/rubric/f2.ts';
import { judge_element } from '../src/rubric/f3.ts';
import { specify_condition } from '../src/rubric/f4.ts';
import { spread_piece } from '../src/rubric/f6.ts';
import { 봉인2_부류 } from '../src/rubric/sealed/group.ts';

const 논제 = '[라]~[사]를 입장이 유사한 두 부류로 묶어 그 중 한 입장을 선택해 요약하고, 이를 바탕으로 다른 입장을 비판하시오. (1,001자 이상~1,100자 이하, 배점 60점)';
const 단락 = {
  라: '과거가 현재를 도울 수 있는가? 죽은 자가 산 자를 구할 수 있는가? 이후 이 소설을 쓰는 동안, 실제로 과거가 현재를 돕고 있다고, 죽은 자들이 산 자를 구하고 있다고 느낀 순간들이 있었다. 인간의 잔혹성과 존엄함 사이에서, 두 벼랑 사이를 있는 불가능한 허공의 길을 건너리면 죽은 자들의 도움이 필요했다.',
  마: '어느 날 한 왕이 이런 생각을 하게 되었다. 가장 필요한 사람은 전하와 지금 함께 있는 사람입니다. 그 외에 누구와 어떤 인연을 맺게 될지는 아무도 모르기 때문입니다. 가장 중요한 일은 함께 있는 사람에게 선을 베푸는 일입니다.',
  바: '요즈음 한두 젊은이들이 원나라 명나라 때의 경박한 글들을 모방해서 글을 짓고는 스스로 뛰어난 문장가인 것처럼 자부한다. 반드시 치유에는 옛날의 경전을 공부하여 밑바탕을 세워야 한다.',
  사: '자, 한번 따져나 보세. 옛날로 말미암이 지금 것을 본다면 지금 것이 보잘것없기야 하지. 그렇지만 그 옛날도 당시에는 또 하나의 지금이었을 뿐이라네. 우리보다 앞선 옛날, 박제화된 그때 거기를 맹목적으로 추수할 것이 아니라 바로 지금 여기에 충실하는 것이 백번 옳지 않겠나? 그래야만 나의 지금은 또 훗날의 옛날이 될 것이 아니겠는가?',
};

describe('부류 판정 — 대립 축 어휘 (sealed/group.ts)', () => {
  it('과거현재: [라]·[바] 과거 중시 / [마]·[사] 현재 중시', () => {
    const r = 봉인2_부류(Object.entries(단락).map(([라벨, 텍스트]) => ({ 라벨, 텍스트 })));
    assert.ok(r);
    assert.deepEqual(r.부류.map((g) => [g.이름, g.단락]), [['과거 중시', ['라', '바']], ['현재 중시', ['마', '사']]]);
  });
  it('「아니라」 앞 어휘는 반대쪽 — [사]는 옛날이 넷이어도 현재 쪽', () => {
    const r = 봉인2_부류([{ 라벨: '라', 텍스트: 단락.라 }, { 라벨: '사', 텍스트: 단락.사 }]);
    assert.ok(r && r.점수.사 < 0);
  });
  it('축 어휘가 없는 단락이 있으면 묶지 않는다', () => {
    assert.equal(봉인2_부류([{ 라벨: '가', 텍스트: '사과는 빨갛다.' }, { 라벨: '나', 텍스트: '지금 여기.' }]), null);
  });
});

describe('분류형 논제 — 4구간 조각', () => {
  const 입력 = f2_input_from_v2(recognizeV2Analysis(논제));
  assert.ok(입력.ok);
  const 부류 = 봉인2_부류(Object.entries(단락).map(([라벨, 텍스트]) => ({ 라벨, 텍스트 })));
  const 참조단락 = ['라', '마', '바', '사'].map((d) => ({ 단락: d, 단락급소: `[${d}]` }));
  const 조각 = derive_pieces(입력.물음, 입력.k, { ...입력.인식, 참조단락, 부류, 연결문장: [], 단락연결: [] }, '인문사회국어');
  const 파트 = (p: string) => 조각.filter((c) => c.파트 === p);

  it('근거대기 = 참조 단락 넷 · 논제 낱말(「이」 「바탕으로」 분량) 조각 없음', () => {
    assert.deepEqual(파트('근거대기').map((c) => c.제시문?.단락), ['라', '마', '바', '사']);
    assert.ok(파트('근거대기').every((c) => c.node === null));
  });
  it('역할 조각도 F3 요소 · F6 모범조각틀을 지난다 (노드 없음)', () => {
    for (const c of [...파트('세우기'), ...파트('풀기')]) {
      const 요소 = judge_element(c, '인문사회국어');
      assert.ok(spread_piece({ ...c, 요소 }, 입력.k, '인문사회국어').length > 0);
    }
  });
  it('세우기 = 묶음 + 선택요약', () => {
    assert.deepEqual(파트('세우기').map((c) => `${c.id}:${c.역할}`), ['세우기-1:묶음', '세우기-2:선택요약']);
    assert.match(specify_condition(파트('세우기')[0], '인문사회국어'), /과거 중시: \[라\]·\[바\] \/ 현재 중시: \[마\]·\[사\]/);
  });
  it('논리펼치기 = 상대 부류 단락마다 상대비판(2) + 인정재반박', () => {
    assert.deepEqual(파트('풀기').map((c) => c.역할), ['상대비판', '상대비판', '인정재반박']);
    assert.ok(파트('풀기').every((c) => c.구간 === '논리펼치기'));
  });
  it('답표현하기 = 마지막 급소 하나 · 경로 = 참조 단락 → 논제 → 목적지', () => {
    const 답 = 파트('답구하기');
    assert.equal(답.length, 1);
    const 경로 = 답[0].경로!;
    assert.deepEqual(경로.slice(0, 4).map((p) => p.단락), ['라', '마', '바', '사']);
    assert.equal(경로.at(-1)!.색, 'k');
    assert.match(경로.at(-1)!.실체, /다른 입장/);
  });
});
