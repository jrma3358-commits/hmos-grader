// 제시문 핵심 한 줄 · 제시문 간 관계(봉인⑧) — 5·6단계 키워드 입력창 위 (오종래 2026-10-21).
// 논제가 먼저 (2026-10-21 확정): 봉인⑨ 요구 → 요구에 닿는 제시문 부분(급소 → 논제 B, 조사 뗀 어절 겹침) → 같은 소문항에 걸린 쌍만 관계.
// 안 닿는 제시문은 도구 · 빈 핵심 (제시문 전체 급소로 돌아가지 않는다).

import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { passage_cores, type 핵심소문항 } from '../src/thesis/passage_core.ts';
import type { 급소단락 } from '../src/thesis/relate.ts';

const 단락 = (단락: string, 급소: string, 소문항: string | null, 표기 = 급소): 급소단락 => ({ 단락, 자리: 0, 급소, 열쇠: 급소, 소문항: [소문항], 표기 });
const 소 = (번호: string, 텍스트: string, 급소: string[], 제시문: string[], 종류: 핵심소문항['요구'][0]['종류'] = '도구'): 핵심소문항 => ({ 번호, 텍스트, 급소, 요구: [{ 종류, 제시문 }] });

describe('제시문 핵심 · 관계 — 논제 먼저 (오종래 2026-10-21)', () => {
  it('4단계 연결 단락 급소가 닿으면 논제 덩어리 표기, 역할은 봉인⑨ 요구 종류', () => {
    const r = passage_cores(
      [{ id: '가', 텍스트: '자유무역은 교역을 넓힌다.' }, { id: '나', 텍스트: '자유무역의 효과는 크다.' }],
      [단락('가', '자유무역', '1', '자유무역이 미치는 영향'), 단락('나', '자유무역의 효과', '1')],
      [소('1', '자유무역이 미치는 영향을 비판하시오.', ['자유무역이 미치는 영향'], ['가', '나'], '표적')],
    );
    assert.deepEqual(r.핵심.map((x) => [x.id, x.핵심, x.출처, x.역할]), [['가', ['자유무역이 미치는 영향'], '급소', '표적'], ['나', ['자유무역의 효과'], '급소', '표적']]);
    assert.deepEqual(r.관계.map((x) => [x.a, x.b, x.유형, x.소문항]), [['가', '나', '유사', '1']]);
  });

  it('급소가 안 닿고 급소 아닌 논제 B가 2어절 이상 겹치면 제시문 쪽 겹친 실체 (조사 뗀 어절)', () => {
    const r = passage_cores(
      [{ id: '나', 텍스트: 'A국은 수입을 늘렸다. 무역상대국은 A국의 보호무역 조치가 원칙을 훼손한다고 주장한다.' }],
      [],
      [소('1', 'A국의 보호무역 조치가 낳은 손실을 줄이기 위해, B국이 시행한 대응조치를 설명하시오.', ['B국이 시행한 대응조치'], ['나'])],
    );
    assert.equal(r.핵심[0].출처, '논제 B');
    assert.deepEqual(r.핵심[0].핵심, ['A국의 보호무역 조치']);
  });

  it('B 실체끼리는 봉인 「B수렴」(~으로·~로·~에)도 떼고 맞댄다 — 「정책으로」 ↔ 「정책이」 (2026-10-21 확정)', () => {
    const r = passage_cores(
      [{ id: '나', 텍스트: '무역상대국은 A국의 보호무역 정책이 원칙을 훼손한다고 주장한다.' }],
      [],
      [소('1', 'A국의 보호무역 정책으로 인한 손실을 줄이기 위해, B국이 시행한 대응조치를 설명하시오.', ['B국이 시행한 대응조치'], ['나'])],
    );
    assert.equal(r.핵심[0].출처, '논제 B');
    assert.deepEqual(r.핵심[0].핵심, ['A국의 보호무역 정책']);
  });

  it('공통 발문(도구)과 소문항 문장(표적)이 같은 제시문을 부르면 역할은 표적 — 봉인⑨ 순서', () => {
    const r = passage_cores(
      [{ id: '나', 텍스트: '' }],
      [단락('나', '찬성 이유', '3')],
      [{ 번호: '3', 텍스트: '', 급소: [], 요구: [{ 종류: '도구', 제시문: ['나'] }, { 종류: '표적', 제시문: ['나'] }] }],
    );
    assert.equal(r.핵심[0].역할, '표적');
  });

  it('1어절만 겹치면 닿지 않는다 — 안 닿는 제시문은 도구 · 빈 핵심, 부르지 않은 소문항은 보지 않는다', () => {
    const r = passage_cores(
      [{ id: '가', 텍스트: 'D국은 새로운 정책을 폈다.' }, { id: '나', 텍스트: '정책이 바뀌었다.' }],
      [],
      [소('1', 'C국이 시행한 정책을 설명하시오.', ['C국이 시행한 정책'], ['가'])],
    );
    assert.deepEqual(r.핵심.map((x) => [x.id, x.핵심, x.출처, x.역할]), [['가', [], null, '도구'], ['나', [], null, '도구']]);
    assert.deepEqual(r.관계, []);
  });

  it('관계는 같은 소문항에 함께 걸린 쌍만 — 다른 소문항에 따로 걸린 쌍은 대조하지 않는다', () => {
    const r = passage_cores(
      [{ id: '가', 텍스트: '' }, { id: '나', 텍스트: '' }, { id: '다', 텍스트: '' }],
      [단락('가', '자유', '1'), 단락('나', '평등', '1'), 단락('다', '정의', '2')],
      [소('1', '', [], ['가', '나']), 소('2', '', [], ['다'])],
    );
    assert.deepEqual(r.관계.map((x) => [x.a, x.b, x.유형, x.소문항]), [['가', '나', '대비', '1']]);
  });
});
