// C·논술 논제 → 공통 발문 + 소문항 (오종래 2026-10-13: 소문항마다 따로 인식, 공통 발문은 떼어 낸다)

import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { split_thesis } from '../src/thesis/split.ts';

const 사회논술 = `[문항 1] 제시문 [가], [나], [다]를 참고하여 다음의 물음에 답하시오.
(1-1) 자유무역이 국가의 경제에 미치는 긍정적인 영향을 경제주체별로 구분하여 설명하시오.
(1-2) A국의 보호무역 정책으로 인한 손실을 줄이기 위해, B국이 시행한 대응조치는 무엇인지 설명하시오.

[문항 2] 제시문 [가], [나], [라], [마]를 참고하여 다음의 물음에 답하시오.
(2-1) C국과 같은 원자재 중심의 수출국이 겪는 구조적 약점을 제시하시오.
(2-2) D국이 시행한 정책이 자국의 경제에 어떤 도움이 될 수 있는지 설명하시오.`;

describe('split_thesis', () => {
  it('문항 머리마다 공통 발문을 떼고 소문항을 나눈다', () => {
    const r = split_thesis(사회논술);
    assert.deepEqual(
      r.map((s) => s.번호),
      ['1-1', '1-2', '2-1', '2-2'],
    );
    assert.equal(r[0].공통발문, '[문항 1] 제시문 [가], [나], [다]를 참고하여 다음의 물음에 답하시오.');
    assert.equal(r[3].공통발문, '[문항 2] 제시문 [가], [나], [라], [마]를 참고하여 다음의 물음에 답하시오.');
  });

  it('소문항 텍스트에는 번호도 공통 발문도 없다', () => {
    const r = split_thesis(사회논술);
    assert.equal(r[0].텍스트, '자유무역이 국가의 경제에 미치는 긍정적인 영향을 경제주체별로 구분하여 설명하시오.');
    assert.equal(r[1].텍스트, 'A국의 보호무역 정책으로 인한 손실을 줄이기 위해, B국이 시행한 대응조치는 무엇인지 설명하시오.');
    assert.ok(r.every((s) => !s.텍스트.includes('참고하여') && !s.텍스트.includes('[문항')));
  });

  it('참조 제시문은 공통 발문에서 물려받는다', () => {
    const r = split_thesis(사회논술);
    assert.deepEqual(r[0].참조, ['가', '나', '다']);
    assert.deepEqual(r[2].참조, ['가', '나', '라', '마']);
  });

  it('소문항 자신의 참조가 공통 발문보다 먼저다', () => {
    const r = split_thesis('제시문 (가)를 참고하여 답하시오. (1-1) 첫째를 설명하시오. (1-2) 제시문 (나)를 바탕으로 둘째를 쓰시오.');
    assert.deepEqual(r.map((s) => s.참조), [['가'], ['나']]);
    assert.equal(r[1].공통발문, '제시문 (가)를 참고하여 답하시오.');
  });

  it('번호가 없으면 논제 전체가 소문항 하나', () => {
    assert.deepEqual(split_thesis('자유무역의 영향을 설명하시오.'), [
      { 번호: null, 텍스트: '자유무역의 영향을 설명하시오.', 공통발문: '', 참조: [] },
    ]);
  });

  it('문장 안의 괄호 숫자는 번호가 아니다', () => {
    const r = split_thesis('함수 f(1-2)의 값과 관련된 개념을 설명하시오.');
    assert.equal(r.length, 1);
    assert.equal(r[0].번호, null);
  });

  it('빈 논제는 빈 배열', () => {
    assert.deepEqual(split_thesis('  '), []);
  });
});

// [오종래 2026-10-14] 5단계 ② 서술복잡 처방(소문항 계단)으로 나눈 논제는 계단마다 인식한다
describe('split_thesis — 계단 (1)(2)(3)', () => {
  it('번호 없는 논제의 계단은 계단마다 — 번호 「1」「2」「3」', () => {
    const r = split_thesis('(1) 환경의 변화를 쓰시오. (2) 그 변화 때문에 겪는 약점을 제시하시오. (3) 물가 상승의 이유를 설명하시오.');
    assert.deepEqual(r.map((s) => [s.번호, s.텍스트]), [
      ['1', '환경의 변화를 쓰시오.'],
      ['2', '그 변화 때문에 겪는 약점을 제시하시오.'],
      ['3', '물가 상승의 이유를 설명하시오.'],
    ]);
  });

  it('문장 가운데의 「(1)의 변화」는 계단이 아니다', () => {
    const r = split_thesis('(1) 변화를 쓰시오. (2) (1)의 변화 때문에 겪는 약점을 제시하시오.');
    assert.deepEqual(r.map((s) => s.번호), ['1', '2']);
    assert.equal(r[1].텍스트, '(1)의 변화 때문에 겪는 약점을 제시하시오.');
  });

  it('소문항 안의 계단은 「소문항-N」, 공통 발문과 참조를 물려받는다', () => {
    const r = split_thesis('[문항 2] 제시문 [가], [라]를 참고하여 다음의 물음에 답하시오.\n(2-1) (1) 변화를 쓰시오. (2) 약점을 제시하시오.\n(2-2) 정책을 설명하시오.');
    assert.deepEqual(r.map((s) => [s.번호, s.텍스트, s.참조]), [
      ['2-1-1', '변화를 쓰시오.', ['가', '라']],
      ['2-1-2', '약점을 제시하시오.', ['가', '라']],
      ['2-2', '정책을 설명하시오.', ['가', '라']],
    ]);
    assert.equal(r[0].공통발문, '[문항 2] 제시문 [가], [라]를 참고하여 다음의 물음에 답하시오.');
  });

  it('첫 계단 앞 글은 계단의 발문 — 공통 발문에 잇고 참조도 거기서', () => {
    const r = split_thesis('(1-1) 제시문 [다]를 보고 답하시오. (1) 첫째를 쓰시오. (2) 둘째를 쓰시오.');
    assert.deepEqual(r.map((s) => [s.번호, s.텍스트, s.공통발문, s.참조]), [
      ['1-1-1', '첫째를 쓰시오.', '제시문 [다]를 보고 답하시오.', ['다']],
      ['1-1-2', '둘째를 쓰시오.', '제시문 [다]를 보고 답하시오.', ['다']],
    ]);
  });

  it('문장 안의 괄호 한 숫자도 계단이 아니다', () => {
    assert.deepEqual(split_thesis('함수 f(1)의 값을 설명하시오.').map((s) => s.번호), [null]);
  });
});
