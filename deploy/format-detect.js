// 문제 형식 자동 판별 [오종래 2026-10-20 확정] — 교사가 먼저 종류(객관식 · 주관식 · 서술형 · 논술형)를 고르면 그 안에서 자동 판별한다:
//   객관식 → A-1 · 주관식 → A-2 · 서술형 → 수식·단위 s/h × 소문항 수 1/2 · 논술형 → 제시문 머리 × 수식 (C-2a · C-1a · C-2b)
// 종류 없이 부르면(서버 — 형식 없는 채점 요청) 아래 순서 전체로 판별한다. 교사가 형식을 바꿀 수 있되 기본은 자동.
//   1단계 객관식 표지: ①②③④⑤ · 「고르시오」 · 「옳은 것은」 · 「맞는 것은」 → A-1 (선택형)
//   2단계 단답형 표지: 빈칸 ( ) · ___ · 「쓰시오」 + 답이 단어·숫자 수준 → A-2 (단답형)
//   3단계 논술형 표지: 「논제」 · 「다음을 읽고 답하시오」 · 총배점 20점+ · 제시문 머리 (가)·[가]·〈가〉 (2026-10-20 추가) → 논술형 C
//         제시문 머리 있고 수식 → C-2a · 머리 있고 서술 → C-1a · 머리 없고 수식 → C-2b · 머리 없고 서술 → 서술형 B로 내려감
//   4단계 서술형 계열: 수식 · 단위(N·g·mol·m/s·℃ 등) · 「=」 · 숫자+단위 → 수리과학(s), 없으면 인문사회(h)
//   5단계 소문항 수: 1개 → B-s1 / B-h1 · 2개+ → B-s2 / B-h2
// 문항분석(/dashboard) · 질문 설계 도구(/tools) · 채점 대시보드(/dashboard2)는 <script src="/format-detect.js">로, 서버는 require로 같은 파일을 쓴다.
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.HMOS형식판별 = api;
})(typeof self !== 'undefined' ? self : this, function () {
  // 원문자 선택지 — 서술형·논술 소문항 머리(①②)와 섞이지 않게 ①~⑤ 중 넷 이상일 때만 선택지로 본다
  const 선택지기호 = /[①②③④⑤]/g;
  const 객관식말 = /고르시오|옳은\s*것은|맞는\s*것은/;
  // 빈칸 — 속이 빈 괄호 「( )」 · 밑줄 3개 이상
  const 빈칸 = /[(（]\s*[)）]|_{3,}/;
  const 쓰시오 = /쓰시오/;
  // 「쓰시오」라도 서술을 요구하면 단답이 아니다 (까닭을 쓰시오 · 풀이 과정을 쓰시오 …)
  const 서술요구 = /서술|설명|논하|논술|풀이|과정|이유|까닭|근거|견해|의견|비교|분석|평가|요약/;
  const 논술말 = /논제|다음을\s*읽고\s*(?:물음에\s*)?답하시오/;
  // 제시문 머리 — 줄 앞 (가) [가] <가> 〈가〉 【가】 · 자모 (ㄱ)(ㄴ) · 앞에 「제시문」이 붙은 「제시문 (가)」 (엔진 제시문 id와 같은 가~하 · ㄱ~ㅎ)
  const 제시문머리 = /(?:^|\n)\s*(?:제시문\s*)?[(\[<〈【]\s*[가나다라마바사아자차카타파하ㄱ-ㅎ]\s*[)\]>〉】]/;
  // 수식 — 변수·연산자·함수 꼴. 인문 글의 연도·퍼센트(2020년 · 30%)는 수식이 아니다
  const 수식들 = [
    /[a-zA-Z]\s*\(\s*[a-zA-Z0-9]\s*\)/,           // f(x) · g(1)
    /[a-zA-Z0-9)]\s*[\^²³]\s*/,                    // x^2 · x² · (a+b)³
    /[√∫∑Σ∏π≤≥≠±∞]/,                               // 기호
    /\\(?:frac|sqrt|int|sum|lim|le|ge)/,           // LaTeX
    /\b(?:lim|log|ln|sin|cos|tan)\b/,
    /[a-zA-Z]\s*[+\-*/×÷]\s*[a-zA-Z0-9(]/,         // x+1 · a-b · x/2
    /[0-9)]\s*[+*×÷]\s*[a-zA-Z0-9(]/,              // 2+3 · 3×x
    /[0-9)]\s*[-/]\s*[a-zA-Z(]/,                   // 2-x · 1/x (숫자-숫자는 소문항 1-1 · 날짜 10/20이라 뺀다)
  ];
  // 단위 — 숫자 뒤에 붙은 과학 단위 (뒤에 영문자가 이어지면 단위가 아니다)
  const 숫자단위 = /\d\s*(?:m\/s²?|m\/s\^2|km\/h|kg|mg|g|mol|mL|ml|L|km|cm|mm|nm|m|N|J|kJ|W|kW|V|mV|A|mA|Ω|Hz|Pa|kPa|atm|K|℃|°C|s|cal|kcal|M)(?![a-zA-Z])/;
  const 단위기호 = /℃|°C|m\/s|mol\b/;
  const 등호 = /=/;

  // 글자 수 조건 「(950±150자)」는 수식이 아니다
  const 글자수조건 = /\d+\s*±\s*\d+\s*자/g;
  const 수식있음 = (글) => { const t = 글.replace(글자수조건, ''); return 수식들.some((r) => r.test(t)) || 등호.test(t); };
  const 수리표지 = (글) => 수식있음(글) || 숫자단위.test(글) || 단위기호.test(글);

  /** 배점 — 「[N점]」「(N점)」「N점」 값들. 머리 배점이 나머지 합과 같으면(문항 30점 = 15 + 15) 머리 배점만, 아니면 합 */
  function 배점합(글) {
    const vs = [...글.matchAll(/(\d+(?:\.\d+)?)\s*점/g)].map((m) => Number(m[1])).filter((v) => v > 0 && v < 1000);
    if (!vs.length) return 0;
    const 큰 = Math.max(...vs), 합 = vs.reduce((a, b) => a + b, 0);
    return 큰 * 2 === 합 && vs.length > 1 ? 큰 : 합;
  }

  /** 소문항 수 — 줄 머리 (1) · 1) · [1] · ① · 1-1 · (1-1) · [문제 1-1], 또는 글 안 띄어쓴 「(1) … (2)」. 번호가 다른 것만 센다.
   *  N-M 꼴이 있으면 그것만 센다 — 「[문제 1]」은 공통 발문 머리 */
  function 소문항수(글) {
    const 번호 = new Set(), 가지 = new Set();
    const 원 = '①②③④⑤⑥⑦⑧⑨⑩';
    for (const m of 글.matchAll(/(?:^|\n)\s*(?:[(\[]\s*(?:문제|문항)?\s*(\d{1,2}(?:-\d{1,2})?)\s*[)\]]|(?:문제|문항)?\s*(\d{1,2}(?:-\d{1,2})?)\s*\))/g)) 번호.add(m[1] || m[2]);
    for (const m of 글.matchAll(/(?:^|\n)\s*(?:문제|문항)?\s*(\d{1,2}-\d{1,2})(?=[\s.)\]])/g)) 번호.add(m[1]);
    for (const m of 글.matchAll(/(?:^|\n)\s*([①-⑩])/g)) 번호.add(String(원.indexOf(m[1]) + 1));
    for (const m of 글.matchAll(/(?:^|[\s.?。])\((\d{1,2})\)\s/g)) 번호.add(m[1]);
    for (const v of 번호) if (v.includes('-')) 가지.add(v);
    return Math.max(1, (가지.size ? 가지 : 번호).size);
  }

  /** 소문항 나누기 — 줄 머리 번호((1) · 1) · [1] · ① · 1-1 · [문제 1-1])로 자른다. 첫 번호 앞 글은 공통 발문(머리).
   *  N-M 꼴이 있으면 그것만 자른다. 소문항 배점 = 그 조각의 「[N점]」「(N점)」 */
  function 소문항나누기(글) {
    const t = String(글 || '');
    const 머리꼴 = /(?:^|\n)[ \t]*(?:[(\[][ \t]*(?:문제|문항)?[ \t]*(\d{1,2}(?:-\d{1,2})?)[ \t]*[)\]]|(?:문제|문항)?[ \t]*(\d{1,2}-\d{1,2})(?=[\s.)\]])|(\d{1,2})\)|([①-⑩]))/g;
    let 자리 = [...t.matchAll(머리꼴)].map((m) => ({ i: m.index + (m[0].startsWith('\n') ? 1 : 0), 번호: m[1] || m[2] || m[3] || m[4] }));
    if (자리.some((x) => x.번호.includes('-'))) 자리 = 자리.filter((x) => x.번호.includes('-'));
    if (자리.length < 2) return null;
    const 소문항 = 자리.map((x, k) => {
      const 조각 = t.slice(x.i, k + 1 < 자리.length ? 자리[k + 1].i : t.length).trim();
      const 점 = 조각.match(/[\[(]\s*(\d+(?:\.\d+)?)\s*점\s*[\])]/);
      return { 번호: x.번호, 글: 조각, 배점: 점 ? Number(점[1]) : null };
    });
    return { 머리: t.slice(0, 자리[0].i).trim(), 소문항 };
  }

  // [오종래 2026-10-20 확정] 교사가 먼저 종류 넷 중 하나를 고르고, 그 안에서 자동 판별한다
  const 종류들 = { 객관식: ['A-1'], 주관식: ['A-2'], 서술형: ['B-s1', 'B-s2', 'B-h1', 'B-h2'], 논술형: ['C-1a', 'C-2a', 'C-2b'] };
  /** 형식 → 종류 (A-1 → 객관식 …) */
  const 종류of = (형식) => Object.keys(종류들).find((k) => 종류들[k].includes(형식)) || null;

  /** 서술형 — 수식·단위 있으면 s, 없으면 h × 소문항 1개 → 1, 2개+ → 2 */
  function 서술형판별(문항, 전체) {
    const 계열 = 수리표지(전체) ? 's' : 'h';
    const 소문항 = 소문항수(문항);
    return {
      형식: `B-${계열}${소문항 >= 2 ? 2 : 1}`, 계열, 소문항,
      근거: [계열 === 's' ? '수식·단위 포함 → 수리과학' : '수식·단위 없음 → 인문사회', `소문항 ${소문항}개`],
    };
  }
  /** 논술형 — 제시문 머리 × 수식. 머리 없고 서술(인문논술·제시문 없음)은 형식표에 없어 C-1a로 두고 확인을 단다 */
  function 논술형판별(전체, 따로제시문) {
    const 머리 = 전체.match(제시문머리);
    const 제시문 = !!따로제시문 || !!머리;
    const 수식 = 수식있음(전체);
    const 근거 = [머리 ? `제시문 머리 「${머리[0].trim()}」` : 따로제시문 ? '제시문 칸' : '제시문 머리 없음', 수식 ? '수식 포함' : '서술 중심'];
    if (!제시문 && !수식) 근거.push('제시문 없는 인문논술 형식은 없음 — C-1a로 둠, 제시문 머리를 확인하세요');
    return { 형식: 수식 ? (제시문 ? 'C-2a' : 'C-2b') : 'C-1a', 근거, 계열: 수식 ? 's' : 'h' };
  }

  /**
   * 형식 판별. 글 = 문항 원문(제시문이 섞여 있어도 된다).
   * 옵션: 종류 (교사가 고른 객관식·주관식·서술형·논술형 — 있으면 그 안에서만 판별) · 제시문 (따로 받은 제시문 글) · 총배점 · 정답
   *   종류가 없으면(서버가 형식 없는 요청을 받을 때) 객관식 → 단답형 → 논술형 → 서술형 순서 전체 판별
   * 돌려주는 값: { 형식, 단계, 근거, 계열?, 소문항? } — 서술형·논술형인데 글이 비었으면 형식 null
   */
  function 판별(글, 옵션 = {}) {
    const 문항 = String(글 || '');
    const 따로제시문 = String(옵션.제시문 || '').trim();
    const 전체 = 따로제시문 ? 문항 + '\n' + 따로제시문 : 문항;
    const 종류 = 종류들[옵션.종류] ? 옵션.종류 : null;
    if (종류 === '객관식') return { 형식: 'A-1', 단계: 1, 근거: ['교사 선택 객관식'] };
    if (종류 === '주관식') return { 형식: 'A-2', 단계: 2, 근거: ['교사 선택 주관식'] };
    if (!전체.trim()) return { 형식: null, 단계: 0, 근거: [] };
    if (종류 === '서술형') { const r = 서술형판별(문항, 전체); return { ...r, 단계: 5, 근거: ['교사 선택 서술형', ...r.근거] }; }
    if (종류 === '논술형') { const r = 논술형판별(전체, 따로제시문); return { ...r, 단계: 3, 근거: ['교사 선택 논술형', ...r.근거] }; }

    // 1단계 객관식
    const 원문자 = new Set(전체.match(선택지기호) || []);
    if (원문자.size >= 4) return { 형식: 'A-1', 단계: 1, 근거: [`선택지 ${[...원문자].sort().join('')}`] };
    const 객 = 전체.match(객관식말);
    if (객) return { 형식: 'A-1', 단계: 1, 근거: [`「${객[0]}」`] };

    // 2단계 단답형
    const 칸 = 전체.match(빈칸);
    if (칸) return { 형식: 'A-2', 단계: 2, 근거: [`빈칸 「${칸[0]}」`] };
    if (쓰시오.test(전체)) {
      const 정답 = String(옵션.정답 || '').trim();
      // 정답이 있으면 그 길이로(단어·숫자 수준 = 15자 이하 · 문장 끝 없음), 없으면 서술을 요구하는 말이 없을 때
      const 짧은답 = 정답 ? 정답.length <= 15 && !/[.다요]$/.test(정답) : !서술요구.test(전체);
      if (짧은답) return { 형식: 'A-2', 단계: 2, 근거: ['「쓰시오」', 정답 ? `정답 「${정답}」 단어·숫자 수준` : '서술 요구 말 없음'] };
    }

    // 3단계 논술형
    const 총배점 = Number(옵션.총배점) > 0 ? Number(옵션.총배점) : 배점합(문항);
    const 논 = 전체.match(논술말);
    // [오종래 2026-10-20 확정] 제시문 머리((가) · [가] · 〈가〉 …)도 논술형 표지 — 있으면 제시문 있음 (채점 대시보드의 따로 넣은 제시문 칸도 있음)
    const 머리 = 전체.match(제시문머리);
    const 제시문 = !!따로제시문 || !!머리;
    if (논 || 총배점 >= 20 || 제시문) {
      const 수식 = 수식있음(전체);
      const 근거 = [논 ? `「${논[0]}」` : 총배점 >= 20 ? `총배점 ${총배점}점` : null, 머리 ? `제시문 머리 「${머리[0].trim()}」` : 따로제시문 ? '제시문 칸' : '제시문 머리 없음', 수식 ? '수식 포함' : '서술 중심'].filter(Boolean);
      // 수리: 머리 있음 → C-2a · 없음 → C-2b / 인문: 머리 있음 → C-1a · 없음 → 서술형 B로 내려간다 (제시문 없는 인문논술 C-1b는 형식표에 없다)
      if (수식 || 제시문) return { 형식: 수식 ? (제시문 ? 'C-2a' : 'C-2b') : 'C-1a', 단계: 3, 근거, 계열: 수식 ? 's' : 'h' };
    }

    // 4·5단계 서술형
    return { ...서술형판별(문항, 전체), 단계: 5 };
  }

  /** 채점 대시보드·서버 채점 형식(B-s1·B-s2·B-h1·B-h2·C1·C2)으로 — 객관식·단답형은 채점 형식이 없다(null) */
  const 채점형식으로 = (형식) => (!형식 || 형식[0] === 'A' ? null : 형식 === 'C-1a' ? 'C1' : /^C-2/.test(형식) ? 'C2' : 형식);

  return { 판별, 종류들, 종류of, 채점형식으로, 소문항수, 소문항나누기, 배점합, 수식있음, 수리표지 };
});
