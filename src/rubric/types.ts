// 루브릭 모듈의 자료구조 — 정본: 봉인/HMOS_루브릭_구현명세-3.md §1·§2
import type { Color } from '../fq/types.ts';
import type { PathNode } from '../fq/v2/graph.ts';
import type { 경우의수문항, 나머지조건, 다항식조건, 문자이차식, 이차식 } from './multipath.ts';

export type 파트 = '근거대기' | '세우기' | '풀기' | '답구하기';
export type 요소 = Lowercase<Color> | 'k';
export type 수행질 = '정확성';

/** 급소 — v2 pivot에서 온다. 이 모듈은 다시 계산하지 않는다 (§1 주의) */
export interface 급소K {
  /** 질문이 요구하는 실체 = pivot.node.entity */
  실체: string;
  node: PathNode;
  /** 엔진 pivot의 핵심어 (앞 쉼표·공백을 뗀 실체 등) — 서술·논술형 ④ 흔적 판정에 쓴다 */
  keyword?: string;
}

/**
 * 서술·논술형 ④ 답구하기의 경로 표지 하나 (오종래 2026-10-14) — 제시문 단락급소 → 논제에서 K 앞 노드 → K.
 * 흔적 = 이 실체 글자가 답안에 남았는가
 */
export interface 경로표지 {
  출처: '제시문' | '논제';
  /** 5색 표지 — 제시문 단락급소는 b, 논제 노드는 노드 색, 마지막은 k */
  색: 요소;
  실체: string;
  /** 제시문 단락 라벨 (출처가 제시문일 때) */
  단락?: string;
  /** K(마지막 표지)만 — 흔적으로 보는 핵심어 = 급소 실체의 마지막 명사 (오종래 2026-10-14) */
  핵심어?: string;
}

/** 엔진 제시문 정합이 이 소문항 급소(노드)와 이은 단락 — align_passage 연결 그대로 */
export interface 급소단락연결 {
  /** 연결의 급소 노드 id (급소덩어리 B) */
  노드: string;
  단락: string;
  단락급소: string;
}

/**
 * 인문논술 세우기의 근거 — 제시문 연결 단락의 문장 하나 (오종래 2026-10-14).
 * 단락·단락급소는 엔진 제시문 정합(align_passage) 산출 그대로다.
 */
export interface 근거문장 {
  /** 단락 라벨 (가·나… 또는 #순번) */
  단락: string;
  /** 엔진이 그 단락에서 잡은 단락 급소 — 이 조각의 실체 */
  단락급소: string;
  문장: string;
}

/** 5색 인식 결과 — v2 출력을 그대로 받는다 */
export interface 인식결과 {
  /** form.colors (문장 순서) */
  조합: Color[];
  /** graph.nodes — ①②에서 «호출된 객체»로 센다 (§3 F2) */
  nodes: PathNode[];
  /**
   * 인문논술(C·논술, 계열 인문사회국어)에서만 — 이 소문항 급소와 엔진이 연결한 제시문 단락의 문장 전부.
   * 계열이 인문사회국어면 ② 세우기는 이 문장 수로 센다 (없으면 조각 없음). 수리는 쓰지 않는다 (봉인② 계열별 파트 구조, 오종래 2026-10-14)
   */
  연결문장?: 근거문장[];
  /** 엔진 급소 전부 (pivot.pivots, 급소 복수) — 서술·논술형 ④ 답구하기는 급소마다 조각 하나 (오종래 2026-10-14). 없으면 k 하나 */
  급소들?: 급소K[];
  /** 서술·논술형 ④ 경로의 제시문 부분 — 엔진 정합이 급소 노드와 이은 단락급소. 없으면 논제 경로만 */
  단락연결?: 급소단락연결[];
  /** 단계형 (1)(2)(3) — 앞 소문항의 급소. 인문이면 ① 근거대기에 「앞 결과」 조각으로 이어받는다 (오종래 2026-10-14) */
  앞급소?: { 번호: string | null; 실체: string }[];
  /** 서술형 B — 교사 모범답안의 세우기 이후 ~ 답구하기 이전 줄 (순서대로, solve_lines.ts). 줄마다 ③ 풀기 조각 하나 — 수리도 (오종래 2026-10-16) */
  교사풀기?: string[];
  /** 수리 — 교사 모범답안 줄 나누기 (solve_lines.ts classify_math_lines, 오종래 2026-10-16 q5).
   *  「~하면」 줄 = ① 근거대기 조각 · 등식 줄 = ② 세우기 조각 · ③ 풀기 없음(세우기=풀기) · 「∴」 줄 = ④ 답구하기의 모범 값 */
  교사줄?: { 근거대기: string[]; 세우기: string[]; 풀기?: string[]; 답: 모범답 | null };
  /** 수리 — 문항의 이차방정식 (수 계수, multipath.ts parse_quadratic). ② 세우기 줄 조각의 다경로 검증에 쓴다 (2026-10-16) */
  원식?: 이차식 | null;
  /** 수리 — 문항의 다항식 · 나머지 조건 (multipath.ts parse_polynomial_conditions, 2026-10-16 q7) */
  다항식?: 다항식조건 | null;
  /** 수리 — 경우의 수 문항 (multipath.ts parse_counting_item, 2026-10-17 q3). 모범답안 줄이 있으면 노드 조각 없이 줄 조각으로 (안 A) */
  경우의수?: 경우의수문항 | null;
}

/** 수리 ④ 답구하기 모범 값 — 모범답안 「∴」 줄과 그 줄의 「x=값」들. 학생 답 값과 직접 대조한다 (오종래 2026-10-16 q5) */
export interface 모범답 {
  줄: string;
  값: string[];
  /** 「∴」 없이 마지막 줄 끝 수가 답 (2026-10-16 q6) — 값은 수 하나, 학생 답도 끝 수로 대조 */
  끝값?: boolean;
}

/** F1 산출 (f1.ts project_parts) */
export type 파트별물음 = Record<파트, string>;

/** 조각 (§2) */
export interface 조각 {
  id: string;
  파트: 파트;
  요소: 요소 | null;
  수행질: 수행질 | null;
  확인물음: string;
  충족조건: string;
  is_중심: boolean;
  /** 이 조각을 낸 인식 노드 (①②). 노드에서 오지 않는 조각(③④ 등)은 null */
  node: PathNode | null;
  /** 인문논술 ② 세우기 — 이 조각을 낸 제시문 문장 (이때 node는 null) */
  근거?: 근거문장;
  /** 서술·논술형 ④ 답구하기 — 제시문 → 논제 → K 경로 표지 (마지막이 K) */
  경로?: 경로표지[];
  /** 인문논술 ① 근거대기 — 4단계 엔진이 연결한 제시문 단락 급소 (이때 node는 null, 실체 = 단락급소) */
  제시문?: { 단락: string; 단락급소: string };
  /** 단계형 ① 근거대기 — 앞 소문항의 급소 K를 이어받은 조각 (이때 node는 null, 실체 = 앞 급소, 오종래 2026-10-14) */
  앞결과?: { 번호: string | null; 실체: string };
  /** 서술형 B ③ 풀기 — 교사 모범답안의 풀기 줄 하나 (이때 node는 null, 판정은 교사, 오종래 2026-10-16) */
  풀기글?: string;
  /** 수리 ①② — 교사 모범답안 줄 하나 (「~하면」 줄 · 등식 줄). node는 null, 판정은 교사 (오종래 2026-10-16 q5) */
  줄글?: string;
  /** 수리 ④ — 모범답안 「∴」 줄 값. 있으면 학생 답 값과 직접 대조, 불일치면 X (오종래 2026-10-16 q5) */
  모범답?: 모범답;
  /** 수리 ② 세우기 줄 — 원식이 있으면 학생 답의 다경로(인수분해 · 완전제곱식 · 근의 공식 1·2)를 엔진이 검증 (2026-10-16) */
  원식?: 이차식;
  /** 수리 ② 세우기 판별식 줄(「D=…」) — 문자 계수 원식(모범답안의 「x²+2x+k-1=0」). 학생의 D · D/4 사슬을 엔진이 검증 (2026-10-16 q4 학생 2) */
  판별식원식?: 문자이차식;
  /** 수리 ② 세우기 방정식 줄(「x²+2x+k-1=0」) — 문자 계수 원식. 학생이 세운 방정식이 같은지 엔진이 검증 (2026-10-16 q4 학생 2) */
  방정식원식?: 문자이차식;
  /** 수리 ① 나머지 조건 조각 — 「x-2로 나누었을 때 나머지가 1」 → 학생이 f(2)=1을 썼는가 (2026-10-16 q7) */
  나머지조건?: 나머지조건;
  /** 수리 ① 다항식 정의 조각 — 학생이 f(x)를 같은 다항식으로 정의했는가 (q7) */
  정의다항식?: 다항식조건;
  /** 수리 ② 나머지 정리 줄 — 「f(2)=4+4+a=1」의 값이 다항식에서 나온 값과 같은가 (q7) */
  나머지다항식?: 다항식조건;
  /** 수리 경우의 수 문항 (2026-10-17 q3) — ① 같은 것이 있는 순열(÷2!) 조각 · ② 줄의 식 검증 */
  경우의수?: 경우의수문항;
  배점: number;
  모범조각: string;
}

/** F2 출력 — 충족조건(F4)·배점(F5)·모범조각(F6)은 뒤 단계가 채운다 */
export type 조각뼈대 = Omit<조각, '충족조건' | '배점' | '모범조각'>;

export type 계열 = '수리' | '인문사회국어';

/**
 * 문항유형 — 1차 필터(문항분석 명세서-2 §2·§3)의 절차를 가르는 축. 계열(수리/인문사회국어)과 별개다.
 * [오종래 2026-09-30] 단독문제 → 서술형 절차(§2)
 *                     계단식 단계형 → 소문항마다 따로 서술형 절차(§2)
 *                     인문사회논술 → 논술형 절차(§3)
 */
export type 문항유형 = '단독문제' | '계단식 단계형' | '인문사회논술';

/** F5 출력 — 배점이 붙은 조각 */
export type 배점조각 = 조각뼈대 & { 배점: number };
