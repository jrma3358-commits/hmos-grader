/**
 * [오종래 2026-10-14] 서술·논술형 ④ 답구하기 — 완전일치가 아니라 표지 흔적 도달.
 * 급소 K 흔적 + 경로(제시문 단락급소 → 논제 K 앞 노드) 흔적 하나 이상이 답안에 남았는가. 경로가 K뿐이면 K 흔적만
 */
function 경로충족조건(경로: 경로표지[]): string {
  const K = 경로[경로.length - 1];
  const 앞 = 경로.slice(0, -1);
  const 표 = (p: 경로표지) => `${p.색}「${p.실체}」${p.단락 ? `[${p.단락}]` : ''}`;
  // 급소 흔적 = K 핵심어(급소 실체의 마지막 명사, 2026-10-14)
  const 급소 = K.핵심어 && K.핵심어 !== K.실체 ? `「${K.실체}」(핵심어 「${K.핵심어}」)` : `「${K.실체}」`;
  return 앞.length
    ? `급소 ${급소}에 닿았다 — 경로 ${[...앞, K].map(표).join(' → ')} 위에서 급소 흔적과 경로 표지 흔적 하나 이상이 답안에 남아 있다.`
    : `급소 ${급소}에 닿았다 — 급소 흔적이 답안에 남아 있다.`;
}

export function 봉인6_충족조건(조각: 조각뼈대, 경계: 경계, _계열: 계열): string {
  if (조각.파트 === '답구하기' && 경계 === '급소도달' && 조각.경로?.length) return 경로충족조건(조각.경로);
  const 틀 = 충족조건틀[조각.파트][경계];
  if (!틀.includes('{실체}')) return 틀;
  const 실체 = 조각.node?.entity.trim() ?? '';
  if (실체 === '') {
    throw new SealedError(`[봉인⑥] ${조각.id}(${조각.파트}): {실체}를 채울 노드 실체가 비어 있습니다.`);
  }
  return 틀.replaceAll('{실체}', 실체);
}
