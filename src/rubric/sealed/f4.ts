/**
 * [오종래 2026-10-14] 서술·논술형 ④ 답구하기 — 완전일치가 아니라 표지 흔적 도달.
 * 급소 K 흔적 + 경로(제시문 단락급소 → 논제 K 앞 노드) 흔적 하나 이상이 답안에 남았는가. 경로가 K뿐이면 K 흔적만
 */
function 경로충족조건(경로: 경로표지[]): string {
  const K = 경로[경로.length - 1];
  const 앞 = 경로.slice(0, -1);
  const 표 = (p: 경로표지) => `${p.색}「${p.실체}」${p.단락 ? `[${p.단락}]` : ''}`;
  // 급소 흔적 = K 핵심어(급소 실체의 마지막 명사, 2026-10-14)
  const 급소 = K.핵심어 && K.핵심어 !== K.실체 ? `「${K.실체}」(핵심어 「${K.핵심어}」)` : `「${K.실체}」`;
  return 앞.length
    ? `급소 ${급소}에 닿았다 — 경로 ${[...앞, K].map(표).join(' → ')} 위에서 급소 흔적과 경로 표지 흔적 하나 이상이 답안에 남아 있다.`
    : `급소 ${급소}에 닿았다 — 급소 흔적이 답안에 남아 있다.`;
}

/**
 * [오종래 2026-10-23] 인문 분류형 역할 조각 — 어느 부류를 골랐는지는 채점 때 학생 답에서 읽는다 (판정은 교사).
 * 엔진 부류가 있으면 참고로 붙인다
 */
function 역할충족조건(조각: 조각뼈대): string {
  const 부류 = 조각.부류 ? ` (엔진 부류 — ${조각.부류.부류.map((g) => `${g.이름}: ${g.단락.map((d) => `[${d}]`).join('·')}`).join(' / ')})` : '';
  switch (조각.역할) {
    case '묶음': return `제시문을 입장이 유사한 두 부류로 바르게 묶었다${부류}.`;
    case '선택요약': return '선택한 부류 안 제시문들의 공통 논지를 정확히 요약했다.';
    case '상대비판': return `상대 부류의 제시문 하나를 선택한 입장에 바탕해 비판했다 — 상대 부류 단락마다 하나${부류}.`;
    case '인정재반박': return '상대 입장의 타당한 점을 인정한 뒤 재반박했다.';
    // 선택·적용형 (오종래 2026-10-23)
    case '고른관점': return `고른 관점(${(조각.관점후보 ?? []).map((p) => `[${p.단락}]`).join(' 또는 ')})의 핵심 개념을 소화해 서술했다.`;
    case '대상': return `적용 대상${조각.적용대상 ? ` [${조각.적용대상.단락}]` : ''}의 구절을 근거로 가져왔다.`;
    case '관점선택': return '두 관점 중 하나를 분명히 골라 해석의 기준으로 세웠다.';
    case '관점요약': return '고른 관점의 논지를 해석에 앞서 정확히 세웠다.';
    case '적용해석': return '적용 대상의 구절 하나를 고른 관점의 개념으로 풀어 그 뜻을 판단했다 — 서로 다른 구절마다 하나.';
    case '관점일관': return '해석의 근거로 고르지 않은 관점의 개념을 끌어오지 않았다.';
    default: return '';
  }
}

export function 봉인6_충족조건(조각: 조각뼈대, 경계: 경계, _계열: 계열): string {
  if (조각.파트 === '답구하기' && 경계 === '급소도달' && 조각.경로?.length) return 경로충족조건(조각.경로);
  if (조각.역할) return 역할충족조건(조각);
  const 틀 = 충족조건틀[조각.파트][경계];
  // [오종래 2026-10-16] 서술형 B ③ 풀기 — 교사 모범답안의 그 풀기 줄을 틀 뒤에 붙인다 (판정은 교사)
  if (조각.풀기글) return `${틀} — 모범답안 ${조각.id}: 「${조각.풀기글}」`;
  // [오종래 2026-10-16 q5] 수리 모범답안 줄 조각(①「~하면」 줄 · ② 등식 줄) — 실체 자리에 그 줄 (판정은 교사)
  if (조각.줄글) return 틀.includes('{실체}') ? 틀.replaceAll('{실체}', 조각.줄글) : `${틀} — 모범답안 줄: 「${조각.줄글}」`;
  // [오종래 2026-10-16 q5] 수리 ④ 모범 값 — 학생 답 값과 직접 대조
  if (조각.모범답) return `${틀} — 모범 값 ${조각.모범답.값.join(', ')} (모범답안 「${조각.모범답.줄}」)`;
  if (!틀.includes('{실체}')) return 틀;
  // 인문논술 ① 제시문 단락 급소 조각은 노드가 없다 — 실체 = 단락 급소 (2026-10-14)
  // 실체 머리의 쉼표·공백은 뗀다 (「제시하고, 국내 물가…」의 쉼표가 실체에 남는다, 2026-10-14)
  const 실체 = (조각.node?.entity ?? 조각.제시문?.단락급소 ?? 조각.앞결과?.실체 ?? '').trim().replace(/^[,，]\s*/, '');
  if (실체 === '') {
    throw new SealedError(`[봉인⑥] ${조각.id}(${조각.파트}): {실체}를 채울 노드 실체가 비어 있습니다.`);
  }
  return 틀.replaceAll('{실체}', 실체);
}
