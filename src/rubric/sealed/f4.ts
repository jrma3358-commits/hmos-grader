// [봉인⑥] 이 조각을 «맞췄다»고 볼 이분(O/X) 경계를 글로 적는다. 오종래가 채운다.
// 경계(완전일치/급소도달)는 계열이 이미 갈라서 넘겨준다 — 여기서는 그 경계를 이 조각에 맞춰 적는 규칙만 정한다.
// [오종래 2026-09-30] 파트 × 경계 충족조건 틀. {실체} 자리는 조각 노드의 entity로 채운다.
import { SealedError } from '../../fq/sealed/index.ts';
import type { 경계 } from '../f4.ts';
import type { 계열, 조각뼈대, 파트 } from '../types.ts';

export const 충족조건틀: Readonly<Record<파트, Record<경계, string>>> = {
  근거대기: {
    완전일치: '{실체}의 개념을 제대로 이해하고 있다.',
    급소도달: '{실체}에 담긴 핵심논리를 정확히 이해하고 있다.',
  },
  세우기: {
    완전일치: '주어진 조건을 식으로 정확히 표현했다.',
    급소도달: '논지를 정확히 서술하고 있다.',
  },
  풀기: {
    완전일치: '식의 전개와 계산 결과가 모두 정확했다.',
    급소도달: '논지의 전개가 논리적으로 정확하다.',
  },
  답구하기: {
    완전일치: '질문의 급소에서 요구된 값과 일치했다.',
    급소도달: '질문이 요구하는 것을 정확히 서술했다.',
  },
};

export function 봉인6_충족조건(조각: 조각뼈대, 경계: 경계, _계열: 계열): string {
  const 틀 = 충족조건틀[조각.파트][경계];
  if (!틀.includes('{실체}')) return 틀;
  const 실체 = 조각.node?.entity.trim() ?? '';
  if (실체 === '') {
    throw new SealedError(`[봉인⑥] ${조각.id}(${조각.파트}): {실체}를 채울 노드 실체가 비어 있습니다.`);
  }
  return 틀.replaceAll('{실체}', 실체);
}
