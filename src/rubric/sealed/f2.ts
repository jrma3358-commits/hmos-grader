/** 실체 머리의 쉼표·공백을 뗀다 (「제시하고, 국내 물가…」의 쉼표) */
const 깨끗이 = (s: string) => s.trim().replace(/^[,，]\s*/, '');

/**
 * 서술·논술형 ④ 경로 — 제시문 단락급소 → 논제에서 K 앞 노드 → K.
 * 논제 노드는 K 앞 직전 Q 뒤부터 (급소 복수면 앞 물음의 노드는 이 경로가 아니다). Q 노드는 넣지 않는다
 */
function 경로of(g: 급소K, 인식: 인식결과): 경로표지[] {
  // 한 단락에 연결이 여럿이면 첫 연결의 단락급소 (link_sentences와 같다)
  const 이은 = (인식.단락연결 ?? []).filter((x) => x.노드 === g.node.id);
  const 제시문 = 이은
    .filter((x, i) => 이은.findIndex((y) => y.단락 === x.단락) === i)
    .map((x): 경로표지 => ({ 출처: '제시문', 색: 'b', 실체: 깨끗이(x.단락급소), 단락: x.단락 }));
  const at = 인식.nodes.findIndex((n) => n.id === g.node.id);
  let from = 0;
  for (let i = 0; i < at; i++) if (인식.nodes[i].color === 'Q') from = i + 1;
  const 논제 = 인식.nodes
    .slice(from, at)
    .filter((n) => n.color !== null && n.color !== 'Q' && 깨끗이(n.entity))
    .map((n): 경로표지 => ({ 출처: '논제', 색: n.color!.toLowerCase() as 요소, 실체: 깨끗이(n.entity) }));
  const K실체 = 깨끗이(g.keyword || g.실체);
  return [...제시문, ...논제, { 출처: '논제', 색: 'k', 실체: K실체, 핵심어: K핵심어(K실체) }];
}

/** 앞뒤 문장부호·따옴표·괄호를 뗀다 */
const 부호떼기 = (s: string) => s.replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, '');

/**
 * 마지막 명사 (오종래 2026-10-14) — 실체의 마지막 어절에서 앞뒤 문장부호·따옴표·괄호를 뗀 것.
 * 형태소 분석기를 쓰지 않는다 (노드 실체는 끝 표지를 이미 뗐다). 떼고 남는 글이 없으면 실체 그대로
 */
export function 마지막명사(실체: string): string {
  const 남은 = 부호떼기(실체.trim().split(/\s+/).pop() ?? '');
  return 남은 || 실체.trim();
}

/**
 * 질문 표지어 — 질문이 무엇을 요구하는지만 가리키는 낱말. K가 이것으로 끝나면 핵심어는 그 앞의 지목 대상 실체 (오종래 2026-10-14).
 * 오종래가 준 목록 그대로 — 늘리려면 오종래가 정한다
 */
export const 질문표지어: readonly string[] = ['이유', '영향', '방안', '차이', '공통점'];

/** 서술 어미 — 「이다」류는 붙은 명사를 남기고(다변화이다 → 다변화), 용언 어미는 그 어절을 통째로 뺀다(성립한다) */
const 지정사어미 = /(이었다|이다|입니다|였다)$/;
const 용언어미 = /(한다|된다|있다|없다)$/;
/** 명사구 경계 — 이 꼴로 끝나는 어절 앞까지가 마지막 명사구다 (조사 · 연결 어미 · 쉼표). 형태소 분석 없이 끝 글자로만 본다 */
const 조사끝 = /(은|는|이|가|을|를|에|에서|로|으로|와|과|도)$/;
const 경계끝 = /(때|면|고|며|서|[,，])$/;

/**
 * K 핵심어 (오종래 2026-10-14) — ④ K 흔적은 이 글자가 답안 문장에 있는가로 본다.
 *  1. 급소가 서술형(「…성립한다」「…이다」)으로 끝나면 서술 어미를 떼고 마지막 명사구.
 *     예) 「'0 ≤ x < π/2일 때 부등식 sinx ≥ xcosx가 성립한다.'」 → 「부등식 sinx ≥ xcosx」
 *  2. 마지막 낱말이 질문 표지어면 그 낱말(과 앞의 「의」)을 떼고 남은 지목 대상 실체 전체.
 *     예) 「국내 물가 상승의 이유」 → 「국내 물가 상승」. 남는 말이 없으면(「영향」) 그대로
 *  3. 그 밖은 마지막 명사. 예) 「B국이 시행한 대응조치」 → 「대응조치」
 */
export function K핵심어(실체: string): string {
  const 글 = 부호떼기(실체.trim());
  let 어절 = 글.split(/\s+/).filter(Boolean);
  if (!어절.length) return 실체.trim();

  // 1. 서술형 끝
  const 끝 = 어절[어절.length - 1];
  const 서술형 = 지정사어미.test(끝) || 용언어미.test(끝);
  if (서술형) {
    if (지정사어미.test(끝) && 끝.replace(지정사어미, '')) 어절 = [...어절.slice(0, -1), 끝.replace(지정사어미, '')];
    else 어절 = 어절.slice(0, -1);
    if (!어절.length) return 마지막명사(실체);
    어절[어절.length - 1] = 어절[어절.length - 1].replace(조사끝, '') || 어절[어절.length - 1];
    let from = 어절.length - 1;
    while (from > 0 && !조사끝.test(어절[from - 1]) && !경계끝.test(어절[from - 1])) from--;
    어절 = 어절.slice(from);
  }

  // 2. 질문 표지어
  if (질문표지어.includes(부호떼기(어절[어절.length - 1]))) {
    const 앞 = 어절.slice(0, -1);
    if (앞.length) {
      앞[앞.length - 1] = 앞[앞.length - 1].replace(/의$/, '');
      const 대상 = 앞.join(' ').trim();
      if (대상) return 대상;
    }
    return 어절.join(' ');
  }

  // 3. 마지막 명사 — 서술형이면 1의 명사구 그대로
  return 서술형 ? 어절.join(' ') : 마지막명사(어절.join(' '));
}

