// [봉인②] 조각 수를 «급소에서 역산한 최소 핵심 수»로 세는 규칙 — 오종래가 채운다.
// 코드가 대신 세지 않는다. 비어 있으면 소리 내어 실패한다 (구현명세 §7).
//
// 채워진 칸 (2026-09-28 오종래):
//   ① 근거대기 = nodes 중 B·D 노드 수
//   ② 세우기   = nodes 중 C·P 노드 수 — 단, Q의 대상(Q 노드 바로 앞 노드)은 ④로 간다
//   ③ 풀기     = ② 조각마다 완성된 식의 결과 하나 (1:1)
//   ④ 답구하기 = Q 노드마다 그 대상 하나 («대상-값 일치» 짝)
//
// [오종래 2026-10-14] 인문논술 — 인식결과.연결문장이 있을 때 (C·논술, 계열 인문사회국어):
//   ② 세우기 = 논제가 요구하는 실체를 서술한 실질 문장 수 — 수리처럼 식 개수가 아니라 논술 서술 실체 문장 수로 역산.
//              그 문장 = 이 소문항 급소와 엔진이 연결한 제시문 단락의 모든 문장. 문장 하나 = 조각 하나 (실체 = 그 단락의 단락 급소)
//   ③ 풀기   = 없음 (배점은 봉인④ 결손재분배로 다른 파트에)
//
// [오종래 2026-10-14] 서술·논술형 ④ 답구하기 (계열 인문사회국어) — 값 일치가 아니라 경로 추적:
//   질문 인식의 최종 급소 K에 닿았는가, 제시문 → 논제 요구 대상 → 논리 네비게이션 경로를 따라왔는가,
//   그 경로 위 5색 표지의 흔적이 답안에 남았는가.
//   대상 = 엔진 급소 K. 급소가 여럿(pivots)이면 조각마다 하나.
//   경로 = 제시문 단락급소(엔진 정합이 그 급소 노드와 이은 단락) → 논제에서 K 앞 노드(앞 물음 Q 뒤부터) → K
//   충족 = K 흔적 + 경로 노드 흔적 하나 이상 (봉인⑥ 틀이 적는다). 수리는 위의 Q 대상 규칙(값 일치) 그대로
import type { Color } from '../../fq/types.ts';
import type { PathNode } from '../../fq/v2/graph.ts';
import type { 경로표지, 계열, 급소K, 인식결과, 조각뼈대, 파트, 파트별물음, 요소 } from '../types.ts';

/** Q의 대상 — Q 노드 바로 앞 노드. 질문이 «무엇을» 요구하는가 */
function qTargets(인식: 인식결과): PathNode[] {
  return 인식.nodes.filter((_, i) => 인식.nodes[i + 1]?.color === 'Q');
}

/** 파트 안의 노드 하나 = 조각 하나. 색이 미결(null)인 노드는 세지 않는다 */
function piecesFromNodes(
  파트: 파트,
  colors: Color[],
  물음: 파트별물음 | null,
  k: 급소K,
  인식: 인식결과,
  exclude: PathNode[] = [],
): 조각뼈대[] {
  return 인식.nodes
    .filter((n) => n.color !== null && colors.includes(n.color) && !exclude.includes(n))
    .map((n, i) => ({
      id: `${파트}-${i + 1}`,
      파트,
      요소: n.color!.toLowerCase() as 요소,
      수행질: null,
      확인물음: 물음?.[파트] ?? '',
      is_중심: n.id === k.node.id,
      node: n,
    }));
}

/** ① 근거대기 = B·D 노드 수 */
export function 봉인2_근거대기(물음: 파트별물음 | null, k: 급소K, 인식: 인식결과): 조각뼈대[] {
  return piecesFromNodes('근거대기', ['B', 'D'], 물음, k, 인식);
}

/** ② 세우기 = C·P 노드 수 (Q의 대상은 빼서 ④로). 인문논술은 연결 단락 문장 수 */
export function 봉인2_세우기(물음: 파트별물음 | null, k: 급소K, 인식: 인식결과): 조각뼈대[] {
  if (인식.연결문장) {
    return 인식.연결문장.map((근거, i) => ({
      id: `세우기-${i + 1}`,
      파트: '세우기',
      요소: 'p',
      수행질: null,
      확인물음: 물음?.세우기 ?? '',
      is_중심: false,
      node: null,
      근거,
    }));
  }
  return piecesFromNodes('세우기', ['C', 'P'], 물음, k, 인식, qTargets(인식));
}

/**
 * ③ 풀기 = 세워진 식(②)마다 «완성된 식의 결과» 하나 — ② 조각과 1:1.
 * 같은 노드를 가리키므로 ②가 X면 그 노드의 ③도 X로 내릴 수 있다 (게이트, 구현명세 §3 F2).
 * 요소가 아니라 수행이다: 요소 null, 수행질 "정확성" (F3 ③).
 */
export function 봉인2_풀기(물음: 파트별물음 | null, k: 급소K, 인식: 인식결과): 조각뼈대[] {
  if (인식.연결문장) return []; // 인문논술은 풀기 없음 (오종래 2026-10-14)
  return 봉인2_세우기(물음, k, 인식).map((p, i) => ({
    id: `풀기-${i + 1}`,
    파트: '풀기',
    요소: null,
    수행질: '정확성',
    확인물음: 물음?.풀기 ?? '',
    is_중심: p.is_중심,
    node: p.node,
  }));
}

/**
 * ④ 답구하기 = Q의 대상마다 조각 하나 («대상-값 일치» 짝).
 * 요소는 k·q 한 몸이라 노드 색에서 가져오지 않는다 — F3(봉인③)이 정한다.
 */
export function 봉인2_답구하기(물음: 파트별물음 | null, k: 급소K, 인식: 인식결과, 계열?: 계열): 조각뼈대[] {
  if (계열 === '인문사회국어') {
    return (인식.급소들 ?? [k]).map((g, i) => ({
      id: `답구하기-${i + 1}`,
      파트: '답구하기',
      요소: null,
      수행질: null,
      확인물음: 물음?.답구하기 ?? '',
      is_중심: true,
      node: g.node,
      경로: 경로of(g, 인식),
    }));
  }
  return qTargets(인식).map((n, i) => ({
    id: `답구하기-${i + 1}`,
    파트: '답구하기',
    요소: null,
    수행질: null,
    확인물음: 물음?.답구하기 ?? '',
    is_중심: n.id === k.node.id,
    node: n,
  }));
}

/** 실체 머리의 쉼표·공백을 뗀다 (「제시하고, 국내 물가…」의 쉼표) */
const 깨끗이 = (s: string) => s.trim().replace(/^[,，]\s*/, '');

/**
 * 서술·논술형 ④ 경로 — 제시문 단락급소 → 논제에서 K 앞 노드 → K.
 * 논제 노드는 K 앞 직전 Q 뒤부터 (급소 복수면 앞 물음의 노드는 이 경로가 아니다). Q 노드는 넣지 않는다
 */
function 경로of(g: 급소K, 인식: 인식결과): 경로표지[] {
  // 한 단락에 연결이 여럿이면 첫 연결의 단락급소 (link_sentences와 같다)
  const 이은 = (인식.단락연결 ?? []).filter((x) => x.노드 === g.node.id);
  const 제시문 = 이은
    .filter((x, i) => 이은.findIndex((y) => y.단락 === x.단락) === i)
    .map((x): 경로표지 => ({ 출처: '제시문', 색: 'b', 실체: 깨끗이(x.단락급소), 단락: x.단락 }));
  const at = 인식.nodes.findIndex((n) => n.id === g.node.id);
  let from = 0;
  for (let i = 0; i < at; i++) if (인식.nodes[i].color === 'Q') from = i + 1;
  const 논제 = 인식.nodes
    .slice(from, at)
    .filter((n) => n.color !== null && n.color !== 'Q' && 깨끗이(n.entity))
    .map((n): 경로표지 => ({ 출처: '논제', 색: n.color!.toLowerCase() as 요소, 실체: 깨끗이(n.entity) }));
  return [...제시문, ...논제, { 출처: '논제', 색: 'k', 실체: 깨끗이(g.keyword || g.실체) }];
}

/** 네 파트 전부. 계열은 ④ 답구하기만 가른다 (서술·논술형 = 인문사회국어) */
export function 봉인2_조각역산(물음: 파트별물음 | null, k: 급소K, 인식: 인식결과, 계열?: 계열): 조각뼈대[] {
  return [
    ...봉인2_근거대기(물음, k, 인식),
    ...봉인2_세우기(물음, k, 인식),
    ...봉인2_풀기(물음, k, 인식),
    ...봉인2_답구하기(물음, k, 인식, 계열),
  ];
}
