// [봉인⑤] 조각을 모범조각으로 펴는 규칙 — 파트가 골라 준 재료를 어떤 글로 펴는지. 오종래가 채운다.
// GJ 검산·되돌림 한도([봉인⑤-a])는 여기 없다 — GJ가 서면 붙인다.
// [오종래 2026-09-30] 파트 × 계열 모범조각 틀. {실체} 자리는 재료 노드의 entity로 채운다.
import { SealedError } from '../../fq/sealed/index.ts';
import type { 재료 } from '../f6.ts';
import type { 계열, 조각뼈대, 파트 } from '../types.ts';

export const 모범조각틀: Readonly<Record<파트, Record<계열, string>>> = {
  근거대기: {
    수리: '{실체}에 대하여 이해하고 있다.',
    인문사회국어: '{실체}에 대하여 이해하고 있다.',
  },
  세우기: {
    수리: '문제의 조건을 식으로 옳게 나타내고 있다.',
    인문사회국어: '논지에 대한 근거의 주장이 적합하다.',
  },
  풀기: {
    수리: '식의 계산 과정이 정확하다.',
    인문사회국어: '논지의 전개 논리와 근거가 모두 타당하다.',
  },
  답구하기: {
    수리: '질문이 요구하는 값을 정확히 구하고 있다.',
    인문사회국어: '논제가 요구하고 있는 논점과 서술한 주장이 정확히 일치한다.',
  },
};

export function 봉인5_모범조각(조각: 조각뼈대, 재료: 재료, 계열: 계열): string {
  const 틀 = 모범조각틀[재료.파트][계열];
  if (!틀.includes('{실체}')) return 틀;
  const 실체 = ('node' in 재료 ? 재료.node.entity : '').trim();
  if (실체 === '') {
    throw new SealedError(`[봉인⑤] ${조각.id}(${재료.파트}): {실체}를 채울 노드 실체가 비어 있습니다.`);
  }
  return 틀.replaceAll('{실체}', 실체);
}
