/** 조각대조에 쓰는 것 — g1.ts가 채워 넘긴다 */
export interface 대조맥락 {
  /** 학생 답을 입구 로직에 태운 인식 노드 */
  답노드: PathNode[];
  질문급소: 급소K;
  계열: 계열;
  루브릭: 조각[];
  /** 앞서 판정된 조각 (세우기가 풀기보다 먼저 온다) */
  앞결과: ReadonlyMap<string, 조각대조>;
}

/** ①②③ — 답 노드 중 entity가 조각 실체와 같은 것이 있는가 */
function 실체대조(조각: 조각, 답노드: PathNode[]): 조각대조 {
  if (조각.node === null) return { 결과: '판정불가', 근거: '조각에 인식 노드가 없습니다.' };
  const 실체 = 조각.node.entity.trim();
  const hit = 답노드.some((n) => n.entity.trim() === 실체);
  return { 결과: hit ? 'O' : 'X', 근거: `답 인식 노드에 "${실체}" ${hit ? '있음' : '없음'}` };
}

/** 실체 머리 쉼표·공백을 뗀다 */
const 깨끗이 = (s: string) => s.trim().replace(/^[,，]\s*/, '');

/** 수리 ④ K 글자 — 머리 쉼표·끝 「의 값」「값」을 떼고 마지막 어절 (「f(2)의 값」 → 「f(2)」, 「상수 a」 → 「a」) */
export function 수리K글자(실체: string): string {
  const 앞 = 깨끗이(실체).replace(/\s*(의\s*)?값$/, '').trim();
  return 앞.split(/\s+/).pop() || 깨끗이(실체);
}

/** 인문 — 조각 실체 글자가 답에 있는가 (노드 실체 · 제시문 단락 급소) */
function 글자대조(학생답: string, 조각: 조각): 조각대조 {
  // 단계형 앞 결과 조각은 앞 급소의 K 핵심어로 맞춘다 — 명제 전체(따옴표·마침표째)는 학생이 그대로 옮겨 쓰지 않는다 (오종래 2026-10-14)
  if (조각.node == null && 조각.앞결과) {
    // 핵심어가 한 글자이거나 한글이 없는 짧은 것(「f(x) ≥ 0」 → 「0」)이면 거짓 O가 나므로 따옴표·마침표만 뗀 명제 전체로
    const 명제 = 깨끗이(조각.앞결과.실체).replace(/^['"‘“「]+|['"’”」]+$/g, '').replace(/[.。]$/, '').replace(/['"’”」]+$/, '').trim();
    const 후보 = K핵심어(명제);
    const 핵심어 = 후보.length >= 2 && (/[가-힣]/.test(후보) || 후보.length >= 4) ? 후보 : 명제;
    if (!핵심어) return { 결과: '판정불가', 근거: '조각에 실체가 없습니다.' };
    const hit = 학생답.includes(핵심어);
    return { 결과: hit ? 'O' : 'X', 근거: `앞 결과 핵심어 「${핵심어}」 ${hit ? '있음' : '없음'}` };
  }
  const 실체 = 깨끗이(조각.node?.entity ?? 조각.제시문?.단락급소 ?? '');
  if (!실체) return { 결과: '판정불가', 근거: '조각에 실체가 없습니다.' };
  const hit = 학생답.includes(실체);
  return { 결과: hit ? 'O' : 'X', 근거: `답에 「${실체}」 ${hit ? '있음' : '없음'}` };
}

/** 인문 ④ — K 핵심어 + 경로 앞 표지 흔적 하나 이상 */
function 경로대조(학생답: string, 조각: 조각): 조각대조 {
  const 경로 = 조각.경로 ?? [];
  if (!경로.length) return 글자대조(학생답, 조각);
  const K = 경로[경로.length - 1];
  const K글자 = K.핵심어 || K.실체;
  const 앞 = 경로.slice(0, -1).map((p) => p.실체);
  const 남은 = 앞.filter((t) => 학생답.includes(t));
  const K있음 = 학생답.includes(K글자);
  const O = K있음 && (!앞.length || 남은.length > 0);
  return {
    결과: O ? 'O' : 'X',
    근거: `급소 핵심어 「${K글자}」 ${K있음 ? '있음' : '없음'}${앞.length ? ` · 경로 흔적 ${남은.length ? 남은.map((t) => `「${t}」`).join(' ') : '없음'}` : ''}`,
  };
}

/**
 * 만남 조건 문장 → 판별식 조건 (오종래 2026-10-16 q4)
 *   「서로 다른 두 점에서 만난다」 → D>0 · 「접한다」 「한 점에서 만난다」 → D=0 · 「만나지 않는다」 → D<0
 * 「서로 다른 두 점」을 「한 점」보다 먼저 본다. 대응이 없으면 null
 */
export function 판별식조건(문장: string): '>' | '=' | '<' | null {
  const t = 문장.replace(/\s+/g, '');
  if (/서로다른두점/.test(t)) return '>';
  if (/만나지않/.test(t)) return '<';
  if (/접한|접하|한점에서만/.test(t)) return '=';
  return null;
}

/** 학생이 판별식 조건을 썼는가 — 「D>0」 또는 「D=-4k+8>0」처럼 D(=식) 뒤 비교 기호와 0 (띄어쓰기 무시) */
export function 판별식썼나(학생답: string, 조건: '>' | '=' | '<'): boolean {
  // 줄은 잇지 않는다 — 띄어쓰기만 무시. D 뒤 식에는 한글·쉼표·「∴」가 들어가지 않는다
  const t = String(학생답 ?? '').replace(/[ \t]+/g, '');
  // 「D/4」도 같은 부호라 판별식 조건이다 · 사슬(「D/4=1-(k-1)=-k+2>0」)도 (2026-10-16 q4 학생 2)
  return [...t.matchAll(/D(?:\/4)?(?:=[^<>=≤≥\n,，∴가-힣]*)*([<>=])0(?![0-9.])/g)].some((m) => m[1] === 조건);
}

export function 봉인6_조각대조(학생답: string, 조각: 조각, 맥락: 대조맥락): 조각대조 {
  if (맥락.계열 === '인문사회국어') {
    switch (조각.파트) {
      case '근거대기':
        return 글자대조(학생답, 조각);
      case '세우기':
      case '풀기':
        return { 결과: '판정불가', 근거: '인문 세우기는 교사가 판정합니다 (오종래 2026-10-14)' };
      case '답구하기':
        return 경로대조(학생답, 조각);
    }
  }
  // [오종래 2026-10-16 q5] 수리 ④ — 모범 값(모범답안 「∴」 줄)이 있으면 학생 답 값과 직접 대조. 불일치면 X (답구하기 0점)
  const 모범 = 조각.모범답;
  if (조각.파트 === '답구하기' && 모범?.값.length) {
    const 줄 = student_answer_line(학생답);
    const 학생값 = answer_values(줄);
    const 같음 = 학생값.length === 모범.값.length && 학생값.every((v, i) => v === 모범.값[i]);
    return {
      결과: 같음 ? 'O' : 'X',
      근거: `모범 값 ${모범.값.join(', ')} · 학생 값 ${학생값.length ? 학생값.join(', ') : '없음'} (「${줄}」) — ${같음 ? '일치' : '불일치'}`,
    };
  }
  // [오종래 2026-10-16 q5] 수리 모범답안 줄 조각(①「~하면」 줄 · ② 등식 줄)은 노드가 없다 — 교사가 판정한다 (범위 확정: 세우기 교사)
  // [오종래 2026-10-16] 수리 ② 세우기 줄 — 원식이 있으면 다경로를 엔진이 수학적으로 검증한다 (multipath.ts).
  //   검증된 경로가 있으면 O(🔆 다경로), 경로 꼴은 있는데 모두 틀리면 X, 아는 경로 꼴이 없으면 판정불가(교사)
  // [오종래 2026-10-16 q4 학생 2] 판별식 줄(「D=…」)이고 원식이 문자 계수면 — 학생의 D · D/4 사슬을 엔진이 검증한다
  // 🔆 다경로는 모범답안 줄의 경로와 다를 때만 — 같은 경로(모범이 인수분해, 학생도 인수분해)는 O만
  const 검증 = 조각.파트 === '세우기' && 조각.줄글 && 조각.node === null
    ? 조각.원식 ? (답: string) => verify_multipath(답, 조각.원식!) : 조각.판별식원식 ? (답: string) => verify_discriminant(답, 조각.판별식원식!) : null
    : null;
  if (검증) {
    const v = 검증(학생답);
    const 모범경로 = 검증(조각.줄글!).경로;
    const 시도 = v.시도.map((t) => `${t.경로} 「${t.식}」 ${t.까닭}`).join(' · ');
    if (v.결과 === 'O') {
      const 맞은 = v.시도.find((t) => t.맞음)!;
      if (v.경로 === 모범경로) return { 결과: 'O', 근거: `모범답안과 같은 경로 — ${v.경로} 검증 (${시도})` };
      return { 결과: 'O', 근거: `🔆 다경로 — ${v.경로} 검증 (${시도})`, 다경로: v.경로, 다경로식: 맞은.식, 다경로까닭: 맞은.까닭 };
    }
    if (v.결과 === 'X') return { 결과: 'X', 근거: `경로 검증 실패 — ${시도}` };
    return { 결과: '판정불가', 근거: `모범답안 줄 「${조각.줄글}」 — 아는 경로 꼴이 없어 교사가 판정합니다` };
  }
  if (조각.줄글 && 조각.node === null) return { 결과: '판정불가', 근거: `모범답안 줄 「${조각.줄글}」 — 교사가 판정합니다` };
  // [오종래 2026-10-16 학생 1] 수리 모범답안 풀기 마디 조각 — 교사가 판정한다. 학생 답의 풀기 마디를 옆에 보인다
  if (조각.파트 === '풀기' && 조각.풀기글 && 조각.node === null) {
    const 학생 = solve_segments(학생답);
    return { 결과: '판정불가', 근거: `모범답안 풀기 「${조각.풀기글}」 · 학생 풀기 ${학생.length ? 학생.map((x) => `「${x}」`).join(' ') : '없음'} — 교사가 판정합니다` };
  }
  if (조각.파트 === '답구하기') {
    const 실체 = 조각.node?.entity ?? 맥락.질문급소.node.entity;
    const 글자 = 수리K글자(실체);
    const hit = 학생답.includes(글자);
    return { 결과: hit ? 'O' : 'X', 근거: `급소 글자 「${글자}」 ${hit ? '있음' : '없음'} (값은 교사 확인)` };
  }
  // [오종래 2026-10-16 q4] 수리 ① 조건 조각 — 만남 조건 문장은 판별식 조건으로 엔진이 직접 판정한다
  if (조각.파트 === '근거대기' && 조각.node) {
    const 조건 = 판별식조건(조각.node.entity);
    if (조건) {
      const hit = 판별식썼나(학생답, 조건);
      return { 결과: hit ? 'O' : 'X', 근거: `조건 「${깨끗이(조각.node.entity)}」 → 판별식 D${조건}0 ${hit ? '있음' : '없음'}` };
    }
  }
  switch (조각.파트) {
    case '근거대기':
    case '세우기':
      return 실체대조(조각, 맥락.답노드);
    case '풀기': {
      const 짝 = 맥락.루브릭.find((c) => c.파트 === '세우기' && c.node !== null && c.node.id === 조각.node?.id);
      const 짝결과 = 짝 && 맥락.앞결과.get(짝.id);
      if (짝결과?.결과 === 'X') return { 결과: 'X', 근거: `짝 세우기 ${짝!.id}가 X → 풀기 X` };
      return 실체대조(조각, 맥락.답노드);
    }
  }
}

