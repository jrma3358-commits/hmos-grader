const 게이트수리: readonly [X파트: 파트, 상한파트: 파트][] = [
  ['답구하기', '풀기'],
  ['풀기', '세우기'],
  ['세우기', '근거대기'],
];
const 게이트인문: readonly [X파트: 파트, 상한파트: 파트][] = [
  ['답구하기', '세우기'],
  ['세우기', '근거대기'],
];

export const 상한비 = 1 / 3;

/** 계열의 게이트 사슬 [X가 난 파트, 상한을 받는 파트]. 풀기 조각이 없으면 풀기를 건너뛴 사슬 (2026-10-16) */
export function 게이트사슬(계열?: 계열, 풀기있음 = true): readonly [파트, 파트][] {
  return 계열 === '인문사회국어' || !풀기있음 ? 게이트인문 : 게이트수리;
}

/** 파트 → 파트점수 상한. 적지 않은 파트는 상한 없음 */
export function 봉인4b_게이트(
  조각별: 조각결과[],
  파트배점: Record<파트, number>,
  계열?: 계열,
  풀기있음 = 조각별.some((r) => r.파트 === '풀기'),
): Partial<Record<파트, number>> {
  const 상한: Partial<Record<파트, number>> = {};
  for (const [X파트, 상한파트] of 게이트사슬(계열, 풀기있음)) {
    if (조각별.some((r) => r.파트 === X파트 && r.결과 === 'X')) {
      상한[상한파트] = Math.round(파트배점[상한파트] * 상한비 * 10) / 10;
    }
  }
  return 상한;
}
