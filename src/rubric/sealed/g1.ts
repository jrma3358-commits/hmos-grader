//     ④ 답구하기 = 경로 흔적 도달: K 핵심어 + 경로 앞 표지 흔적 하나 이상 (답구하기_명세.md 6)
//   수리 — ①②③은 위 2026-09-30 그대로(답 인식 노드 일치), ④는 GJ 대신 K 글자가 학생 답에 있으면 O
//     (K 글자 = 급소 실체에서 머리 쉼표·끝 「의 값」「값」을 떼고 마지막 어절 — 값 자체는 교사가 확인)
import type { PathNode } from '../../fq/v2/graph.ts';
import type { 조각결과 } from '../g1.ts';
import type { 계열, 급소K, 조각, 파트 } from '../types.ts';

export interface 조각대조 {
  결과: 'O' | 'X' | '판정불가';
  /** 자취에 남는 판단 근거 */
  근거: string;
}

/** 조각대조에 쓰는 것 — g1.ts가 채워 넘긴다 */
export interface 대조맥락 {
  /** 학생 답을 입구 로직에 태운 인식 노드 */
  답노드: PathNode[];
  질문급소: 급소K;
  계열: 계열;
  루브릭: 조각[];
  /** 앞서 판정된 조각 (세우기가 풀기보다 먼저 온다) */
  앞결과: ReadonlyMap<string, 조각대조>;
}

/** ①②③ — 답 노드 중 entity가 조각 실체와 같은 것이 있는가 */
function 실체대조(조각: 조각, 답노드: PathNode[]): 조각대조 {
  if (조각.node === null) return { 결과: '판정불가', 근거: '조각에 인식 노드가 없습니다.' };
  const 실체 = 조각.node.entity.trim();
  const hit = 답노드.some((n) => n.entity.trim() === 실체);
  return { 결과: hit ? 'O' : 'X', 근거: `답 인식 노드에 "${실체}" ${hit ? '있음' : '없음'}` };
}

/** 실체 머리 쉼표·공백을 뗀다 */
const 깨끗이 = (s: string) => s.trim().replace(/^[,，]\s*/, '');

/** 수리 ④ K 글자 — 머리 쉼표·끝 「의 값」「값」을 떼고 마지막 어절 (「f(2)의 값」 → 「f(2)」, 「상수 a」 → 「a」) */
export function 수리K글자(실체: string): string {
  const 앞 = 깨끗이(실체).replace(/\s*(의\s*)?값$/, '').trim();
  return 앞.split(/\s+/).pop() || 깨끗이(실체);
}

/** 인문 — 조각 실체 글자가 답에 있는가 (노드 실체 · 제시문 단락 급소) */
function 글자대조(학생답: string, 조각: 조각): 조각대조 {
  const 실체 = 깨끗이(조각.node?.entity ?? 조각.제시문?.단락급소 ?? 조각.앞결과?.실체 ?? ''); // 앞 결과 조각도 글자로 (2026-10-14)
  if (!실체) return { 결과: '판정불가', 근거: '조각에 실체가 없습니다.' };
  const hit = 학생답.includes(실체);
  return { 결과: hit ? 'O' : 'X', 근거: `답에 「${실체}」 ${hit ? '있음' : '없음'}` };
}

/** 인문 ④ — K 핵심어 + 경로 앞 표지 흔적 하나 이상 */
function 경로대조(학생답: string, 조각: 조각): 조각대조 {
  const 경로 = 조각.경로 ?? [];
  if (!경로.length) return 글자대조(학생답, 조각);
  const K = 경로[경로.length - 1];
  const K글자 = K.핵심어 || K.실체;
  const 앞 = 경로.slice(0, -1).map((p) => p.실체);
  const 남은 = 앞.filter((t) => 학생답.includes(t));
  const K있음 = 학생답.includes(K글자);
  const O = K있음 && (!앞.length || 남은.length > 0);
  return {
    결과: O ? 'O' : 'X',
    근거: `급소 핵심어 「${K글자}」 ${K있음 ? '있음' : '없음'}${앞.length ? ` · 경로 흔적 ${남은.length ? 남은.map((t) => `「${t}」`).join(' ') : '없음'}` : ''}`,
  };
}

export function 봉인6_조각대조(학생답: string, 조각: 조각, 맥락: 대조맥락): 조각대조 {
  if (맥락.계열 === '인문사회국어') {
    switch (조각.파트) {
      case '근거대기':
        return 글자대조(학생답, 조각);
      case '세우기':
      case '풀기':
        return { 결과: '판정불가', 근거: '인문 세우기는 교사가 판정합니다 (오종래 2026-10-14)' };
      case '답구하기':
        return 경로대조(학생답, 조각);
    }
  }
  if (조각.파트 === '답구하기') {
    const 실체 = 조각.node?.entity ?? 맥락.질문급소.node.entity;
    const 글자 = 수리K글자(실체);
    const hit = 학생답.includes(글자);
    return { 결과: hit ? 'O' : 'X', 근거: `급소 글자 「${글자}」 ${hit ? '있음' : '없음'} (값은 교사 확인)` };
  }
  switch (조각.파트) {
    case '근거대기':
    case '세우기':
      return 실체대조(조각, 맥락.답노드);
    case '풀기': {
      const 짝 = 맥락.루브릭.find((c) => c.파트 === '세우기' && c.node !== null && c.node.id === 조각.node?.id);
      const 짝결과 = 짝 && 맥락.앞결과.get(짝.id);
      if (짝결과?.결과 === 'X') return { 결과: 'X', 근거: `짝 세우기 ${짝!.id}가 X → 풀기 X` };
      return 실체대조(조각, 맥락.답노드);
    }
  }
}

// [오종래 2026-09-30] 봉인④-b 게이트:
//   답구하기 X → 풀기 상한 · 풀기 X → 세우기 상한 · 세우기 X → 근거대기 상한 (한 칸씩, 번지지 않는다)
//   파트 X = 그 파트 조각 중 X가 하나라도 있음. 판정불가는 상한을 걸지 않는다.
//   상한 = 상한을 받는 파트 배점합의 1/3 (소수 첫째 자리 반올림, ④-a와 같은 자릿수)
// [오종래 2026-10-14] 인문사회국어는 풀기가 없어 사슬을 건너뛰어 잇는다: 답구하기 X → 세우기 상한 · 세우기 X → 근거대기 상한 (1/3 그대로)
const 게이트수리: readonly [X파트: 파트, 상한파트: 파트][] = [
  ['답구하기', '풀기'],
  ['풀기', '세우기'],
  ['세우기', '근거대기'],
];
const 게이트인문: readonly [X파트: 파트, 상한파트: 파트][] = [
  ['답구하기', '세우기'],
  ['세우기', '근거대기'],
];

export const 상한비 = 1 / 3;

/** 계열의 게이트 사슬 [X가 난 파트, 상한을 받는 파트] */
export function 게이트사슬(계열?: 계열): readonly [파트, 파트][] {
  return 계열 === '인문사회국어' ? 게이트인문 : 게이트수리;
}

/** 파트 → 파트점수 상한. 적지 않은 파트는 상한 없음 */
export function 봉인4b_게이트(
  조각별: 조각결과[],
  파트배점: Record<파트, number>,
  계열?: 계열,
): Partial<Record<파트, number>> {
  const 상한: Partial<Record<파트, number>> = {};
  for (const [X파트, 상한파트] of 게이트사슬(계열)) {
    if (조각별.some((r) => r.파트 === X파트 && r.결과 === 'X')) {
      상한[상한파트] = Math.round(파트배점[상한파트] * 상한비 * 10) / 10;
    }
  }
  return 상한;
}
