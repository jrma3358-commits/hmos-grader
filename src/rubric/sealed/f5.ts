// [봉인④] 파트 지수 · [봉인④-a] 반올림 — 오종래가 채운다.
// 지수는 문항마다 바뀌지 않는다(계열마다 고정). 비어 있으면 소리 내어 실패한다 (구현명세 §7).
//
// 채워진 칸 (2026-09-28 오종래):
//   ④   파트 지수 = 근거대기 2 : 세우기 3 : 풀기 2 : 답구하기 2 (⑤표현 제외, 두 계열 공통)
//   ④-a 반올림   = 몫마다 소수 첫째 자리로 반올림, 합이 전체와 맞도록 나머지는 마지막 칸에
//   [오종래 2026-10-15 (가)] ④-a를 큰 나머지 방식으로 바꿈 — 마지막 칸 하나가 나머지를 떠안으면 조각이 많을 때 음수가 된다
//     (C-논술 차별·혐오 표현 문항: 파트 1.1점을 7조각 → 0.2×6 + (-0.1)). 모두 0.1 단위로 내림하고, 모자란 0.1을 버린 끝수가 큰 몫부터 하나씩
// [오종래 2026-09-30] 결손재분배 = 조각이 0개인 파트는 빼고, 조각이 있는 파트끼리 지수 비율대로 총배점을 나눈다
import type { 계열, 파트 } from '../types.ts';

/** [봉인④] 조각 없는 파트의 배점을 조각 있는 파트로 다시 나누는가 */
export const 결손재분배 = true;

const 파트지수: Record<파트, number> = { 근거대기: 2, 세우기: 3, 풀기: 2, 답구하기: 2 };

/** 반올림 자릿수 (소수 첫째 자리) */
const 자릿수 = 1;

const 반올림 = (x: number) => Math.round(x * 10 ** 자릿수) / 10 ** 자릿수;

/** [봉인④·④-계열] 파트 지수 — 계열마다 고정. 계열별 지수가 서기 전까지는 두 계열 공통 */
export function 봉인4_파트지수(_계열: 계열): Record<파트, number> {
  return 파트지수;
}

/**
 * [봉인④-a] 전체를 몫들로 나눌 때 — 큰 나머지 방식 (오종래 2026-10-15 (가)). 몫마다 0.1 단위로 내림하고,
 * 전체와 모자란 만큼을 버린 끝수가 큰 몫부터 0.1씩 하나씩 얹는다. 합은 전체와 맞고 음수가 없다.
 * 끝수가 같으면 뒤 몫 먼저 — 음수가 나지 않던 문항은 옛 규칙(나머지는 마지막 칸)과 같은 배점이 나온다.
 * 총배점 → 파트, 파트 배점 → 조각 두 층 모두에 쓴다.
 */
export function 봉인4a_반올림(전체: number, 몫: number[]): number[] {
  if (!몫.length) return [];
  const 단위 = 10 ** 자릿수;
  // 부동소수 오차(0.30000000000000004 등)를 먼저 걷어 낸 단위 수
  const 칸 = 몫.map((x) => Math.round(x * 단위 * 1e6) / 1e6);
  const 내림 = 칸.map(Math.floor);
  let 모자람 = Math.round(전체 * 단위) - 내림.reduce((a, b) => a + b, 0);
  const 순서 = 칸.map((x, i) => ({ i, 끝수: x - 내림[i] })).sort((a, b) => b.끝수 - a.끝수 || b.i - a.i);
  for (let k = 0; 모자람 > 0 && 순서.length; k = (k + 1) % 순서.length, 모자람--) 내림[순서[k].i]++;
  // 몫의 합이 전체보다 크게 들어온 경우(정상 입력에는 없다) — 끝수가 작은 몫부터, 0 아래로는 내리지 않는다
  for (let k = 순서.length - 1; 모자람 < 0 && k >= 0; k--) if (내림[순서[k].i] > 0) { 내림[순서[k].i]--; 모자람++; }
  return 내림.map((x) => 반올림(x / 단위));
}
