// [봉인] 문항평가 — 분해 중 난 «삐걱» 신호를 경고로 낼지, 판정 기준값은 무엇인지. 오종래가 채운다 (구현명세 §5).
// [오종래 2026-09-30] 세 신호 모두 «경고만» — 생성을 멈추지 않는다 (구현명세 §6 미결 해소).
//                     결손 파트의 배점은 조각이 있는 파트로 다시 나눈다 (sealed/f5.ts 봉인④ 결손재분배).
import type { 삐걱신호 } from '../item_eval.ts';

export function 봉인_문항평가(신호: 삐걱신호): string[] {
  const 경고: string[] = [];
  if (신호.중심없음) {
    경고.push('이 문항에 급소 중심 조각이 없습니다. 채점 기준이 흔들릴 수 있습니다.');
  }
  for (const 파트 of 신호.결손파트) {
    경고.push(`${파트} 파트에 조각이 없습니다. 해당 파트 배점은 배분됩니다.`);
  }
  for (const g of 신호.겹침) {
    경고.push(`${g.파트} 파트에서 ${g.node.entity}가 두 조각 이상에 걸립니다. 중의성을 확인하세요.`);
  }
  return 경고;
}
