/** 받침이 있으면 앞 조사, 없으면 뒤 조사 — 끝 글자가 한글이 아니면 「과(와)」처럼 둘 다 */
function 조사(글: string, 받침: string, 없음: string): string {
  const c = 글.trim().slice(-1).charCodeAt(0) - 0xac00;
  if (!(c >= 0 && c <= 11171)) return `${받침}(${없음})`;
  return c % 28 ? 받침 : 없음;
}
const 과와 = (s: string) => 조사(s, '과', '와');
const 을를 = (s: string) => 조사(s, '을', '를');
const 이가 = (s: string) => 조사(s, '이', '가');

