/**
 * [봉인⑭ ④] 6유형 논제 뼈대 (오종래 2026-10-14 확정). a·b·v는 급소단락의 표기(논제 핵심 덩어리 B, 없으면 급소) — (A) 2026-10-14. 머리는 언제나 「제시문 [A], [B]를 참고하여」 — 엔진이 참조 범위로 읽는다.
 *   비교·대비: [A]의 a와 [B]의 b를 비교하시오.
 *   선택·근거: [A]의 a와 [B]의 b 가운데 하나를 선택하여 선택의 근거를 제시하시오.
 *   비판·인연: [A]의 a의 입장에서 [B]의 b를 비판하시오.
 *   수용·반론: [A]와 [B]에 공통으로 나타나는 c에 담긴 원리를 서술하시오.          (지시 동사는 「서술하시오」 하나뿐)
 *   근거·주장: [F]의 f에서 근거를 들어 [V]의 v에 대한 주장을 논하시오.            (v = 빈 곳, f = 채움)
 *   설명·분석: [V]의 v가 지닌 문제를 분석하고, [F]의 f를 바탕으로 대처 방안을 제시하시오.
 * 뼈대는 엔진에 다시 넣어 두 단락에 연결되고 급소가 B로 서며, 조립설명서 「6유형 분류 기준」으로 제 유형에 드는 것을 확인한 꼴이다 (사회논술_문_1).
 * 쓰지 않는 꼴: 「그 차이를」「그 근거를」(지시어가 급소), 「선택하고,」(동사가 급소), 「비교하여 설명하시오」(비교 노드가 안 섬),
 * 「비판적으로 서술하시오」(지시 동사가 「서술하시오」 하나라 수용·반론에도 듦).
 */
export function 논제뼈대(r: 단락관계, 유형: 논제유형): { 뼈대: string; 실체들: string[] } {
  const [A, B] = [r.앞, r.뒤];
  const 머리 = `제시문 [${A.단락}], [${B.단락}]를 참고하여 `;
  const x = r.실체;
  if (x.관계 === '보완') {
    const 빈 = A.급소 === x.빈곳 ? A : B;
    const 채단락 = x.채움[0].단락;
    const f = x.채움[0].실체;
    const v = 빈.표기;
    if (유형 === '근거·주장') return { 뼈대: `${머리}[${채단락}]의 ${f}에서 근거를 들어 [${빈.단락}]의 ${v}에 대한 주장을 논하시오.`, 실체들: [f, v] };
    return { 뼈대: `${머리}[${빈.단락}]의 ${v}${이가(v)} 지닌 문제를 분석하고, [${채단락}]의 ${f}${을를(f)} 바탕으로 대처 방안을 제시하시오.`, 실체들: [v, f] };
  }
  if (x.관계 === '유사') {
    const c = x.공통[0];
    return { 뼈대: `${머리}[${A.단락}]와 [${B.단락}]에 공통으로 나타나는 ${c}에 담긴 원리를 서술하시오.`, 실체들: [c] };
  }
  const [a, b] = [A.표기, B.표기];
  if (유형 === '비교·대비') return { 뼈대: `${머리}[${A.단락}]의 ${a}${과와(a)} [${B.단락}]의 ${b}${을를(b)} 비교하시오.`, 실체들: [a, b] };
  if (유형 === '비판·인연') return { 뼈대: `${머리}[${A.단락}]의 ${a}의 입장에서 [${B.단락}]의 ${b}${을를(b)} 비판하시오.`, 실체들: [a, b] };
  return { 뼈대: `${머리}[${A.단락}]의 ${a}${과와(a)} [${B.단락}]의 ${b} 가운데 하나를 선택하여 선택의 근거를 제시하시오.`, 실체들: [a, b] };
}

/** 관계의 실체를 한 줄로 — 근거에 쓴다 */
export function 관계실체글(x: 관계실체): string {
  if (x.관계 === '유사') return `공통 근거 ${x.공통.map((t) => `「${t}」`).join('·')}`;
  if (x.관계 === '대비') return `기준 「${x.기준}」 · 차이 「${x.차이[0]}」 ↔ 「${x.차이[1]}」`;
  if (x.관계 === '보완') return `빈 곳 「${x.빈곳}」 · 채움 [${x.채움[0].단락}]「${x.채움[0].실체}」`;
  return `나열 「${x.나열[0]}」 · 「${x.나열[1]}」`;
}

/** ⑤ 추가 → 6단계 추가 논제 후보. 같은 단락 쌍·같은 유형은 먼저 서는 관계 하나로 */
export function 추가후보들(관계들: 단락관계[]): 추가후보[] {
  const 추가 = 관계들.filter((r) => r.판단 === '추가').sort((p, q) => 관계순서.indexOf(p.실체.관계) - 관계순서.indexOf(q.실체.관계));
  const out: 추가후보[] = [];
  for (const r of 추가) {
    for (const 유형 of r.유형) {
      const 단락: [string, string] = [r.앞.단락, r.뒤.단락];
      if (out.some((c) => c.유형 === 유형 && c.단락[0] === 단락[0] && c.단락[1] === 단락[1])) continue;
      out.push({ id: `a${out.length + 1}`, 유형, 관계: r.실체.관계, 단락, ...논제뼈대(r, 유형), 근거: `${r.실체.관계} — ${관계실체글(r.실체)} · ${r.근거}` });
    }
  }
  return out;
}

/** ⑤ 보완 → 5단계 정교화 진단 하나 */
export interface 보완진단 {
  갈래: '보완';
  단위: string | null;
  근거: string;
  /** 끌어들일 단락과 그 급소 */
  단락: string;
  급소: string;
  /** 이미 연결된 단락과 그 급소 */
  연결단락: string;
  연결급소: string;
  관계: 관계유형;
}

/** ⑤ 보완 → 5단계로 넘길 진단. 같은 소문항·같은 끌어들일 단락은 먼저 서는 관계 하나로 */
export function 보완진단들(관계들: 단락관계[]): 보완진단[] {
  const 보완 = 관계들.filter((r) => r.판단 === '보완' && r.끌어들일 && r.연결된).sort((p, q) => 관계순서.indexOf(p.실체.관계) - 관계순서.indexOf(q.실체.관계));
  const out: 보완진단[] = [];
  for (const r of 보완) {
    const [끌, 연] = [r.끌어들일!, r.연결된!];
    if (out.some((d) => d.단위 === r.소문항 && d.단락 === 끌.단락)) continue;
    out.push({
      갈래: '보완',
      단위: r.소문항 ?? null,
      근거: `제시문 [${끌.단락}]의 「${끌.급소}」 — 이미 연결된 [${연.단락}]「${연.급소}」${과와(연.급소)} ${r.실체.관계} 관계, 참조 범위 안 (${관계실체글(r.실체)})`,
      단락: 끌.단락,
      급소: 끌.급소,
      연결단락: 연.단락,
      연결급소: 연.급소,
      관계: r.실체.관계,
    });
  }
  return out;
}

export interface 육단계 {
  /** 유사·대비가 하나도 없으면 true — 비교를 세울 단락 쌍이 없다 (오종래 2026-10-14) */
  비교불가: boolean;
  급소단락: 급소단락[];
  관계: 단락관계[];
  추가후보: 추가후보[];
  보완: 보완진단[];
}

/** [봉인⑭] 6단계 전부 — ①②③ 관계, ④ 뼈대, ⑤ 추가·보완·덮음 */
export function 봉인14_6단계(정합: 정합엔진, passage: PassageRecognition): 육단계 {
  const 관계 = 봉인14_단락관계(정합, passage);
  return {
    비교불가: !관계.some((r) => r.실체.관계 === '유사' || r.실체.관계 === '대비'),
    급소단락: 급소단락들(정합, passage),
    관계,
    추가후보: 추가후보들(관계),
    보완: 보완진단들(관계),
  };
}
