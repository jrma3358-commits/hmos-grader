// 기호뿐인 실체 — 제시문 기호(「(나)」「[가]」)·원문자 기호(「ⓐ」「㉠」)와 그 나열·범위(「ⓐ~ⓓ」「(가), (다), (라)」)만으로 된 노드 실체.
// 대상이 아니라 가리키는 표시다 (오종래 2026-10-15). 5단계 서술복잡 개수(filter/sealed/items.ts)와
// 8단계 ① 근거대기 조각(rubric/sealed/f2.ts)이 같은 판정을 쓴다. 「ⓐ~ⓓ에 담긴 차별적 인식」처럼 기호 뒤에 명사구가 붙으면 기호뿐이 아니다.

const 기호 = String.raw`(?:[\[<(][가-힣][\]>)]|[ⓐ-ⓩⒶ-Ⓩ㉠-㉻])`;
const 기호뿐RE = new RegExp(String.raw`^[\s,]*${기호}(?:\s*(?:[,·ㆍ~∼～-]|및|와|과)\s*${기호})*[\s,]*$`);

export const 기호뿐 = (entity: string): boolean => 기호뿐RE.test(entity);
