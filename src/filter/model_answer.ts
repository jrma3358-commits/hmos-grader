// 모범답안 검증 — 문항분석 명세서-2 §7 (F6 위에 얹힘). 모범답안이 교사가 승인한 급소에 실제로 닿는지 엔진이 확인한다.
// 새 규칙은 없다. 학생답을 채점하는 그 엔진으로 모범답안을 역채점한다:
//   · 조각 전체 커버 — G1 grade (봉인⑥ 조각대조). X인 조각 = 빠진 조각
//   · 급소 도달      — GJ judge_pivot_match (봉인⑤⑥ 급소일치). 경로가 달라도 급소에 닿으면 된다
// 둘 다 서면 확정, 하나라도 X면 불일치(교사 수정 → 재검증), X 없이 판정불가가 있으면 판정불가.
// 모범답안은 심판이 아니라 견본이다 — 확정은 «견본으로서 급소를 제대로 보여준다»는 뜻이다.
// 다경로(§5)는 아직 표시 규칙이 없어 «한 경로의 견본» 명시는 하지 않는다.
import type { 루브릭생성결과 } from '../rubric/assemble.ts';
import { grade } from '../rubric/g1.ts';
import { judge_pivot_match, type 급소판정 } from '../rubric/gj.ts';

export type 검증결과 = '확정' | '불일치' | '판정불가';

export interface 모범답안검증 {
  결과: 검증결과;
  모범답안: string;
  급소도달: 급소판정;
  /** X난 조각 id — 모범답안이 커버하지 못한 조각 */
  빠진조각: string[];
  /** 판정불가 조각 id */
  판정불가조각: string[];
  /** 교사에게 보일 문구. 확정이면 빈 배열 */
  표시: string[];
}

function 급소사유(g: 급소판정): string {
  return g.결과 === '판정불가' ? `모범답안에서 급소가 서지 않음 (${g.실패.flag})` : `답 급소 「${g.답급소.실체}」`;
}

/**
 * 모범답안검증(모범답안, 루브릭생성결과) → 확정 | 불일치 | 판정불가
 * 교사가 쓴 모범답안이든 F6이 편 모범답안이든 같은 길로 잰다.
 * @throws SealedError 봉인④-b·⑤⑥이 비어 있을 때
 */
export function verify_model_answer(모범답안: string, 루브릭: 루브릭생성결과): 모범답안검증 {
  const { 급소, 계열 } = 루브릭;
  const 급소도달 = judge_pivot_match(모범답안, 급소, 계열);
  const 채점 = grade(모범답안, 루브릭.루브릭, 모범답안, 급소, 계열);
  const 조각들 = Object.values(채점.파트별).flatMap((p) => p.조각별);
  const 빠진조각 = 조각들.filter((r) => r.결과 === 'X').map((r) => r.조각id);
  const 판정불가조각 = 채점.판정불가;

  const 표시: string[] = [];
  if (급소도달.결과 !== 'O') {
    표시.push(`모범답안이 급소 「${급소.실체}」에 닿지 않음 — ${급소사유(급소도달)}`);
  }
  if (빠진조각.length) 표시.push(`모범답안이 커버하지 못한 조각: ${빠진조각.join(', ')}`);
  if (판정불가조각.length) 표시.push(`판정불가 조각: ${판정불가조각.join(', ')}`);

  const 결과: 검증결과 =
    급소도달.결과 === 'X' || 빠진조각.length
      ? '불일치'
      : 급소도달.결과 === '판정불가' || 판정불가조각.length
        ? '판정불가'
        : '확정';
  return { 결과, 모범답안, 급소도달, 빠진조각, 판정불가조각, 표시 };
}
