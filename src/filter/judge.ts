// 필터 판정 — 1차 필터 (문항분석 명세서-2 §5). 문항유형에 따라 분석을 부르고 항목을 모아 판정한다.
// 구조로 가리는 항목은 여기, 판단이 드는 항목은 sealed/items.ts([봉인⑩~⑬]).
// [오종래 2026-09-30]
//   · 급소 명확 — PivotFailure면 거르기 (초석1). 뒤 항목은 보지 않는다
//   · 재료 완결(논술형) — 제시문 0개·5개 초과, 또는 논제 요구의 도구·표적이 받은 제시문에 없으면 거르기
//   · 관계 적절(논술형) — 연결점이 하나라도 false면 거르기(악문 신호, 초석2), null이 있으면 재판정
//   · 계단식 단계형 — 소문항 중 하나라도 거르기면 전체 거르기
//   · 전부 통과해도 «통과(교사 확인 대기)»까지만. 루브릭창으로 넘기는 것은 교사 승인(§6)이다
import { analyze_descriptive, type 급소불명거르기, type 서술형분석 } from './descriptive.ts';
import { analyze_essay, type 논술문항, type 논술형분석 } from './essay.ts';
import { 봉인10_관계적절, 봉인11_요소결손, 봉인12_중의성, 봉인13_정교화필요 } from './sealed/items.ts';
import type { 소문항 } from './sealed/stepwise.ts';
import { analyze_stepwise } from './stepwise.ts';

/** [오종래 2026-09-30] 논술형 제시문 상한 — 쌍 비교 수 n(n-1)/2 (§8) */
export const 제시문상한 = 5;

export type 증상 = '급소 명확' | '관계 적절' | '재료 완결' | '요소 결손' | '중의성' | '정교화 필요';
export type 항목판정 = '통과' | '거르기' | '재판정';
export type 최종판정 = '통과(교사 확인 대기)' | '거르기' | '재판정';

export interface 항목결과 {
  증상: 증상;
  판정: 항목판정;
  /** 명세 §0½가 짝지어 준 초석만 적는다 */
  초석?: 1 | 2;
  사유: string;
}

export type 필터입력 =
  | { 유형: '단독문제'; 텍스트: string }
  | { 유형: '계단식 단계형'; 텍스트: string }
  | ({ 유형: '인문사회논술' } & 논술문항);

export interface 필터판정 {
  판정: 최종판정;
  항목: 항목결과[];
  분석: 서술형분석 | 논술형분석 | null;
}

export interface 계단식필터판정 {
  판정: 최종판정;
  소문항: { 소문항: 소문항; 판정: 필터판정 }[];
}

function 묶기(판정들: (항목판정 | 최종판정)[]): 최종판정 {
  if (판정들.includes('거르기')) return '거르기';
  if (판정들.includes('재판정')) return '재판정';
  return '통과(교사 확인 대기)';
}

function 급소불명(r: 급소불명거르기): 필터판정 {
  return {
    판정: '거르기',
    항목: [{ 증상: '급소 명확', 판정: '거르기', 초석: 1, 사유: `${r.실패.flag}: ${r.실패.message}` }],
    분석: null,
  };
}

/** 공통 뒷부분 — 요소 결손·중의성(봉인⑪⑫) → 정교화 필요(봉인⑬) */
function 공통항목(분석: 서술형분석 | 논술형분석, 앞: 항목결과[]): 항목결과[] {
  const 결손 = 봉인11_요소결손(분석);
  const 겹침 = 봉인12_중의성(분석);
  const 항목: 항목결과[] = [
    ...앞,
    결손.length
      ? { 증상: '요소 결손', 판정: '거르기', 사유: `빠진 조건: ${결손.join(', ')}` }
      : { 증상: '요소 결손', 판정: '통과', 사유: '결손 없음' },
    겹침.length
      ? { 증상: '중의성', 판정: '거르기', 사유: `두 조각에 걸친 실체: ${겹침.join(', ')}` }
      : { 증상: '중의성', 판정: '통과', 사유: '겹침 없음' },
  ];
  const 정교화 = 봉인13_정교화필요(항목);
  항목.push(
    정교화
      ? { 증상: '정교화 필요', 판정: '거르기', 사유: '정교화/추가논제 신호' }
      : { 증상: '정교화 필요', 판정: '통과', 사유: '신호 없음' },
  );
  return 항목;
}

/** 서술형(단독문제·계단식 소문항 하나) 판정 */
function judge_descriptive(r: 서술형분석 | 급소불명거르기): 필터판정 {
  if (r.판정 === '거르기') return 급소불명(r);
  const 앞: 항목결과[] = [
    { 증상: '급소 명확', 판정: '통과', 초석: 1, 사유: `급소 「${r.k.실체}」` },
    봉인10_관계적절(r.실체, r.k)
      ? { 증상: '관계 적절', 판정: '통과', 사유: r.실체.요약 }
      : { 증상: '관계 적절', 판정: '거르기', 사유: r.실체.요약 },
  ];
  const 항목 = 공통항목(r, 앞);
  return { 판정: 묶기(항목.map((x) => x.판정)), 항목, 분석: r };
}

function judge_essay(문항: 논술문항): 필터판정 {
  const n = 문항.제시문.length;
  if (n === 0 || n > 제시문상한) {
    return {
      판정: '거르기',
      항목: [{ 증상: '재료 완결', 판정: '거르기', 사유: `제시문 ${n}개 (1~${제시문상한}개여야 함)` }],
      분석: null,
    };
  }

  const r = analyze_essay(문항);
  if (r.판정 === '거르기') return 급소불명(r);

  const ids = new Set(문항.제시문.map((c) => c.id));
  const 없는 = [...new Set(r.연결점.flatMap((c) => [c.요구.도구, c.표적]))].filter((id) => !ids.has(id));
  const 재료: 항목결과 = 없는.length
    ? { 증상: '재료 완결', 판정: '거르기', 사유: `논제가 요구한 제시문이 없음: ${없는.map((x) => `(${x})`).join('')}` }
    : { 증상: '재료 완결', 판정: '통과', 사유: `제시문 ${n}개` };

  const 틈 = r.연결점.filter((c) => c.성립 === false);
  const 미정 = r.연결점.filter((c) => c.성립 === null);
  const 쌍 = (c: (typeof r.연결점)[number]) => `(${c.요구.도구})↔(${c.표적})`;
  const 관계: 항목결과 = 틈.length
    ? {
        증상: '관계 적절',
        판정: '거르기',
        초석: 2,
        사유: `발문-제시문 틈: ${틈.map((c) => `${쌍(c)} 요구 ${c.요구.관계} / 실제 ${c.실제 ?? '없음'}`).join('; ')}`,
      }
    : 미정.length
      ? { 증상: '관계 적절', 판정: '재판정', 초석: 2, 사유: `핵심 결손으로 대조 못 함: ${미정.map(쌍).join(', ')}` }
      : { 증상: '관계 적절', 판정: '통과', 초석: 2, 사유: r.실체.join(' / ') };

  const 앞: 항목결과[] = [
    { 증상: '급소 명확', 판정: '통과', 초석: 1, 사유: `논제 급소 「${r.논제k.실체}」` },
    재료,
    관계,
  ];
  const 항목 = 공통항목(r, 앞);
  return { 판정: 묶기(항목.map((x) => x.판정)), 항목, 분석: r };
}

/**
 * 필터판정(입력) → 통과(교사 확인 대기) | 거르기 | 재판정  (§5)
 * @throws SealedError 봉인②·⑦~⑬이 비어 있을 때
 */
export function judge_item(입력: 필터입력): 필터판정 | 계단식필터판정 {
  switch (입력.유형) {
    case '단독문제':
      return judge_descriptive(analyze_descriptive(입력.텍스트));
    case '계단식 단계형': {
      const 소문항 = analyze_stepwise(입력.텍스트).map((s) => ({ 소문항: s.소문항, 판정: judge_descriptive(s.결과) }));
      return { 판정: 묶기(소문항.map((s) => s.판정.판정)), 소문항 };
    }
    case '인문사회논술':
      return judge_essay(입력);
  }
}
