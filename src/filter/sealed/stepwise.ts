// [봉인⑦] 계단식 단계형 문항을 소문항으로 나누는 규칙.
// [오종래 2026-10-20 확정]
//   · 소문항 번호 (1)(2)가 있으면 각각 독립 소문항으로 나눈다 — 번호 자르기는 논제 소문항 분리(thesis/split.ts split_thesis)와 같다
//   · 앞 소문항 답이 다음 소문항에 필요하면 계단식(이어달리기, relay 적용), 필요 없으면 병렬 독립
//   · 판별: 다음 소문항에 「(1)에서 구한」 · 「위에서 구한」 같은 이어달리기 표지가 있으면 계단식, 없으면 병렬
import { split_thesis } from '../../thesis/split.ts';

export interface 소문항 {
  /** 표시용 번호 (예: "1"). 번호가 없는 한 덩어리면 null */
  번호: string | null;
  /** 급소 인식에 넣을 텍스트 — 번호와 공통 발문을 뗀 소문항 본문 (split_thesis) */
  텍스트: string;
  /** 앞 소문항과의 관계 — 첫 소문항은 null */
  관계: '계단식' | '병렬' | null;
  /** 계단식이면 이어받는 앞 소문항 번호 (표지가 번호를 가리키면 그 번호, 아니면 바로 앞) */
  앞번호?: string | null;
}

/**
 * 이어달리기 표지 — 「(1)에서 구한」 · 「위에서 구한」 · 「앞 문항에서 구한」 · 「[1-3]에서 구한」 (오종래 2026-10-20).
 * 표지가 번호를 가리키면 그 번호, 아니면 null
 */
const 이어달리기표지 = /(?:\(\s*(\d+(?:-\d+)?)\s*\)|\[(?:문제[ \t]*)?(\d+(?:-\d+)?)\]|위|앞[ \t]*(?:소?문항)?)[ \t]*에서[ \t]*구한/;

export function 이어달리기(본문: string): { 번호: string | null } | null {
  const m = 이어달리기표지.exec(본문);
  return m ? { 번호: m[1] ?? m[2] ?? null } : null;
}

/** 소문항 글 하나 — 표지를 떼기 전 본문 (split_thesis가 「[N-M]에서 구한」을 떼면 원문에 남는다) */
const 본문of = (s: ReturnType<typeof split_thesis>[number]) => s.원문 ?? s.텍스트;

export function 봉인7_소문항분리(문항텍스트: string): 소문항[] {
  const 나눔 = split_thesis(문항텍스트);
  return 나눔.map((s, i) => {
    if (i === 0) return { 번호: s.번호, 텍스트: s.텍스트, 관계: null };
    const 표지 = 이어달리기(본문of(s)) ?? (s.이어받기 ? { 번호: s.이어받기.번호 } : null);
    return 표지
      ? { 번호: s.번호, 텍스트: s.텍스트, 관계: '계단식', 앞번호: 표지.번호 ?? 나눔[i - 1].번호 }
      : { 번호: s.번호, 텍스트: s.텍스트, 관계: '병렬' };
  });
}
