// 선생 확인 창 — 교사 자기 검증 (문항분석 명세서-2 §6). 엔진이 판정한 것을 교사가 최종 승인한다.
// 화면 자료를 만들고(make_screen), 글로 그리고(render_screen), 교사 선택을 받아 다음 행선지를 낸다(choose).
// · ①을 골라야만 루브릭창으로 넘어간다. 엔진 단독으로 넘어가지 않는다.
// · ①은 엔진 판정이 «통과(교사 확인 대기)»일 때만 고를 수 있다 — 거르기·재판정을 교사가 ①로 덮지 않는다.
// · ② 표현 수정 → 고친 입력으로 재판정. ③ 정교화 모드·④ 논제 생성 모드는 별도 명세서라 행선지만 낸다.
// · 다경로 지점(§5)은 아직 표시 규칙이 없어 비워 둔다.
import type { 서술형분석 } from './descriptive.ts';
import type { 논술형분석 } from './essay.ts';
import { judge_item, type 계단식필터판정, type 필터입력, type 필터판정, type 최종판정 } from './judge.ts';

export type 선택번호 = 1 | 2 | 3 | 4;

export type 교사선택 = { 번호: 1 } | { 번호: 2; 수정: 필터입력 } | { 번호: 3 } | { 번호: 4 };

export interface 확인화면 {
  입력: 필터입력;
  판정: 필터판정 | 계단식필터판정;
  /** 소문항이 있으면 소문항마다 한 줄 */
  급소: string[];
  실체요약: string[];
  필터판정: 최종판정;
  /** §5 다경로 표시 — 규칙 미구현, 늘 빈 배열 */
  다경로지점: string[];
  선택지: 선택번호[];
}

/** 교사가 ①로 승인한 문항 — 루브릭창의 입장권. choose만 만든다 */
export interface 승인된문항 {
  readonly 승인: '교사 ①';
  readonly 입력: 필터입력;
  readonly 판정: 필터판정 | 계단식필터판정;
}

export type 다음행선지 =
  | { 다음: '루브릭창'; 문항: 승인된문항 }
  | { 다음: '재판정'; 화면: 확인화면 }
  | { 다음: '정교화 모드'; 화면: 확인화면 }
  | { 다음: '논제 생성 모드'; 화면: 확인화면 };

const 서지않음 = '(서지 않음)';

function 급소of(분석: 서술형분석 | 논술형분석 | null): string {
  if (!분석) return 서지않음;
  return 'k' in 분석 ? 분석.k.실체 : 분석.논제k.실체;
}

function 요약of(분석: 서술형분석 | 논술형분석 | null): string[] {
  if (!분석) return [서지않음];
  return 'k' in 분석 ? [분석.실체.요약] : 분석.실체;
}

/** 확인화면(입력) — 필터 판정(§5)을 돌려 화면 자료를 만든다 */
export function make_screen(입력: 필터입력): 확인화면 {
  const 판정 = judge_item(입력);
  const [급소, 실체요약] =
    '소문항' in 판정
      ? [
          판정.소문항.map((s) => `${s.소문항.번호} ${급소of(s.판정.분석)}`),
          판정.소문항.flatMap((s) => 요약of(s.판정.분석).map((x) => `${s.소문항.번호} ${x}`)),
        ]
      : [[급소of(판정.분석)], 요약of(판정.분석)];
  return {
    입력,
    판정,
    급소,
    실체요약,
    필터판정: 판정.판정,
    다경로지점: [],
    선택지: 판정.판정 === '통과(교사 확인 대기)' ? [1, 2, 3, 4] : [2, 3, 4],
  };
}

const 선택문구: Record<선택번호, string> = {
  1: '① 급소가 내 의도와 맞다       → [통과] 루브릭창으로',
  2: '② 급소는 맞으나 표현 수정     → [수정 입력] → 재판정',
  3: '③ 정교화 필요                → [정교화 모드]',
  4: '④ 추가 논제 필요             → [논제 생성 모드]',
};

/** 화면을 글로 (§6 배치) */
export function render_screen(화면: 확인화면): string {
  const 항목들 =
    '소문항' in 화면.판정
      ? 화면.판정.소문항.flatMap((s) => s.판정.항목.map((i) => `${s.소문항.번호} ${i.증상}: ${i.판정} — ${i.사유}`))
      : 화면.판정.항목.map((i) => `${i.증상}: ${i.판정} — ${i.사유}`);
  const 줄 = (이름: string, 값들: string[]) => [`${이름}: ${값들[0] ?? ''}`, ...값들.slice(1).map((v) => `${' '.repeat(이름.length)}  ${v}`)];
  return [
    '[문항 적절성 체크 화면]',
    '',
    ...줄('급소(k)      ', 화면.급소),
    ...줄('실체 요약    ', 화면.실체요약),
    ...줄('필터 판정    ', [화면.필터판정, ...항목들.map((x) => `· ${x}`)]),
    ...줄('다경로 지점  ', 화면.다경로지점.length ? 화면.다경로지점 : ['(표시 규칙 없음)']),
    '',
    '─────────────────────────────',
    '교사 확인:',
    ...화면.선택지.map((n) => `  ${선택문구[n]}`),
    '─────────────────────────────',
  ].join('\n');
}

/**
 * 교사선택(화면, 선택) → 다음 행선지
 * @throws Error 선택지에 없는 번호(엔진 판정이 통과가 아닌데 ①)를 골랐을 때
 */
export function choose(화면: 확인화면, 선택: 교사선택): 다음행선지 {
  if (!화면.선택지.includes(선택.번호)) {
    throw new Error(`선택 ${선택.번호}은(는) 고를 수 없습니다 — 필터 판정이 «${화면.필터판정}»입니다.`);
  }
  switch (선택.번호) {
    case 1:
      return { 다음: '루브릭창', 문항: { 승인: '교사 ①', 입력: 화면.입력, 판정: 화면.판정 } };
    case 2:
      return { 다음: '재판정', 화면: make_screen(선택.수정) };
    case 3:
      return { 다음: '정교화 모드', 화면 };
    case 4:
      return { 다음: '논제 생성 모드', 화면 };
  }
}
